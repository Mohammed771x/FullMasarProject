// 🖌️ مفسّر مسارات SVG — الحدّ الأدنى الكافي
// ══════════════════════════════════════════════════
/// يدعم `M` `L` `C` `Z` بإحداثيات مطلقة، والأرقام بصيغة علمية (`1e-05`).
/// ولا يدعم الأقواس (`A`) ولا الأوامر النسبية — لأن مسارات هذا الملف لا
/// تستعملها، وإضافةُ ما لا يُستعمل ديْنٌ بلا مقابل.
Path _parse(String d) {
  final path = Path();
  int i = 0;
  double cx = 0, cy = 0;

  double num_() {
    while (i < d.length && (d[i] == ' ' || d[i] == ',')) {
      i++;
    }
    final start = i;
    if (i < d.length && (d[i] == '-' || d[i] == '+')) i++;
    while (i < d.length) {
      final c = d[i];
      final isDigit = c.codeUnitAt(0) >= 48 && c.codeUnitAt(0) <= 57;
      if (isDigit || c == '.') {
        i++;
      } else if (c == 'e' || c == 'E') {
        i++;
        if (i < d.length && (d[i] == '-' || d[i] == '+')) i++;
      } else {
        break;
      }
    }
    return double.parse(d.substring(start, i));
  }

  while (i < d.length) {
    final c = d[i];
    if (c == ' ' || c == ',') {
      i++;
      continue;
    }
    switch (c) {
      case 'M':
        i++;
        cx = num_();
        cy = num_();
        path.moveTo(cx, cy);
      case 'L':
        i++;
        cx = num_();
        cy = num_();
        path.lineTo(cx, cy);
      case 'C':
        i++;
        final x1 = num_(), y1 = num_(), x2 = num_(), y2 = num_();
        cx = num_();
        cy = num_();
        path.cubicTo(x1, y1, x2, y2, cx, cy);
      case 'Z':
      case 'z':
        i++;
        path.close();
      default:
        // أمرٌ غير متوقَّع: نتخطّاه بدل أن نرمي — أيقونةٌ ناقصة أهون من
        // شاشةٍ تنهار عند أول مسارٍ فيه حرفٌ لم نحسب له حساباً.
        i++;
    }
  }
  return path;
}

