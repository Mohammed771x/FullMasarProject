class MasarIcon extends StatelessWidget {
  const MasarIcon(this.paths,
      {super.key, required this.size, required this.color});

  final List<IconPath> paths;
  final double size;
  final Color color;

  @override
  Widget build(BuildContext context) => SizedBox(
        width: size,
        height: size,
        child: CustomPaint(painter: _IconPainter(paths, color)),
      );
}

class _IconPainter extends CustomPainter {
  const _IconPainter(this.paths, this.color);
  final List<IconPath> paths;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final k = size.width / MasarIconPaths.frame;
    canvas.save();
    canvas.scale(k);
    for (final p in paths) {
      final paint = Paint()
        ..color = p.opacity == 1 ? color : color.withValues(alpha: p.opacity)
        ..isAntiAlias = true;
      canvas.save();
      canvas.translate(p.dx, p.dy);
      canvas.drawPath(_parse(p.d), paint);
      canvas.restore();
    }
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant _IconPainter old) =>
      old.color != color || !identical(old.paths, paths);
}
