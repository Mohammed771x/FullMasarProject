// ==========================================
// ✅ فاحصُ حقول التوثيق — قاعدةٌ واحدة لكل شاشة
// ==========================================
// 🔴 **العلّة التي عالجها هذا الملف:** كان لكل شاشةٍ فحصُها الخاص، وكانت
//    الثلاثةُ **مختلفة**:
//
//    | الموضع | فحصُ البريد |
//    |---|---|
//    | `signup_flow` | `contains('@') && contains('.')` |
//    | `forgot_password_screen` | `contains('@') && contains('.')` |
//    | `UserSession` | `RegExp(r'^[\w.+-]+@[\w-]+\.[\w.-]+$')` |
//
//    فـ`a@b.` تمرّ من شاشة التسجيل وترفضها `UserSession` بعد **ثلاث
//    خطوات** — الطالبُ اختار دورَه وصفَّه ومساره ثم قيل له «صيغة البريد
//    غير صحيحة» في آخر شاشة، ولا يعرف أين يعود ليصحّح.
//
// ⭐ فالفحصُ هنا **وحده**، وتستعمله الشاشاتُ و`UserSession` معاً — فما
//    تقبله الشاشةُ يقبله اللوجيك، وما ترفضه تُخبر عنه **عند الحقل**.
//
// ⚠️ **ولا فحصَ أمنيّ هنا إطلاقاً.** هذا فحصُ *صيغة* لمنع خطأٍ مطبعيّ.
//    الحمايةُ عند Firebase والقواعد والخادم — انظر `firestore.rules`.
library;

/// فحوصُ حقول التوثيق. تُعيد **رسالةً عربية**، أو `null` حين يصحّ الحقل.
class AuthValidators {
  AuthValidators._();

  /// 📧 صيغةُ البريد.
  ///
  /// ⚠️ **ولمَ لا نتوسّع في التعبير النمطيّ؟** الصيغةُ الكاملة (RFC 5322)
  ///    تعبيرٌ من مئات المحارف يقبل `"a b"@x.com` ويرفض بُرُداً صحيحة
  ///    عملياً. وما يهمّنا خطأُ الطالب المطبعيّ: نسيَ `@`، أو `.`، أو
  ///    كتب مسافة. وما نجح شكلاً وفشل حقيقةً **ترفضه Firebase** بعد نداء.
  static String? email(String raw) {
    final e = raw.trim();
    if (e.isEmpty) return 'اكتب بريدك الإلكتروني';
    if (e.contains(' ')) return 'البريد الإلكتروني لا يحتوي مسافات';
    if (!_email.hasMatch(e)) return 'تحقّق من صيغة البريد الإلكتروني';
    return null;
  }

  /// هل البريد صحيح الصيغة؟ — للمواضع التي تريد قيمةً منطقية.
  static bool isEmail(String raw) => email(raw) == null;

  /// 🙍 الاسمُ الكامل.
  ///
  /// ⚠️ الحدُّ الأعلى **60** ليس رقماً مخترعاً: هو سقفُ `validProfile` في
  ///    `firestore.rules`. واسمٌ أطول تقبله الشاشةُ ترفضه القاعدةُ صامتةً
  ///    فلا يُكتب مستندُ الحساب أصلاً.
  static String? name(String raw) {
    final n = raw.trim();
    if (n.isEmpty) return 'اكتب اسمك الكامل';
    if (n.length < 3) return 'الاسم قصير جداً — اكتب اسمك الكامل';
    if (n.length > 60) return 'الاسم طويل — 60 حرفاً على الأكثر';
    return null;
  }

  /// 🔁 تأكيدُ كلمة المرور.
  static String? confirm(String password, String confirmation) {
    if (confirmation.isEmpty) return 'أعد كتابة كلمة المرور';
    if (password != confirmation) return 'كلمتا المرور غير متطابقتين';
    return null;
  }

  static final RegExp _email = RegExp(r'^[\w.+-]+@[\w-]+\.[\w.-]+$');
}
