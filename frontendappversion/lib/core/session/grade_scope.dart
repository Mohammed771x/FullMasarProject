import 'package:flutter/foundation.dart';

// ==========================================
// 🎓 نطاق الصف — الوحدة التي يُفصل عليها كل شيء
// ==========================================
// **المطلب (قرار المالك):** حسابٌ واحد يرافق الطالب ثلاث سنوات، وكل صفٍّ
// له سجلُّه المستقل تماماً: محادثاته ونتائجه وإحصائياته ومحفوظاته. يبدّل
// الصف من الإعدادات فتتبدّل الأرقام كلها، ويعود بعد سنة فيجد سجلّ صفّه
// القديم كما تركه — **لا يُمسح شيء أبداً، إنما يُفلتَر**.
//
// ⭐ **ولهذا لا تكلفة على فاتورة Firestore إطلاقاً:**
//    كل السجلات تحمل `grade` و`track` أصلاً وتعيش تحت `users/{uid}` نفسه.
//    فالفصلُ **فلترةٌ محلية في Hive** لا مستنداتٌ جديدة ولا قراءاتٌ جديدة —
//    والبديل (حسابٌ لكل صف) كان سيضاعف المستندات والقراءات ثلاثاً ويُفقد
//    الطالبَ سجلَّه كل سنة.
//
// 🔑 **والمسار جزءٌ من النطاق لا الصف وحده:** «ثاني علمي» و«ثاني أدبي»
//    منهجان مختلفان بمواد مختلفة، فخلطُ إحصائياتهما يقول للطالب إن أضعف
//    موادّه مادةٌ لا يدرسها أصلاً.
@immutable
class GradeScope {
  const GradeScope(this.grade, this.track);

  final int grade;
  final String track;

  /// هل ينتمي سجلٌّ بهذا الصف والمسار إلى النطاق؟
  ///
  /// ⚠️ **سجلٌّ بصفٍّ صفر ينتمي لكل نطاق**: تلك سجلّاتُ ما قبل الفصل التي
  ///    لم يكن لها صفٌّ يوم حُفظت. إخفاؤها كان سيعني أن الطالب يفتح التطبيق
  ///    بعد التحديث فيجد محفوظاتِه اختفت — وهو عطبٌ في نظره لا ميزة.
  ///    و[SavedStorage.adoptScopeless] تنسبها لصفّه عند أول دخول فتنتهي الحالة.
  bool includes(int g, String t) => g == 0 || (g == grade && t == track);

  /// مفتاح نصّي مختصر — للكاش والسجلّات.
  String get key => '$grade|$track';

  @override
  bool operator ==(Object other) =>
      other is GradeScope && other.grade == grade && other.track == track;

  @override
  int get hashCode => Object.hash(grade, track);

  @override
  String toString() => 'GradeScope($key)';
}
