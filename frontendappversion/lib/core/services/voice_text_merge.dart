//
// 🔴 **السلوك الذي يصححه:** كان التسجيل الثاني **يمحو** ما في الحقل. والطالب
//    يسجّل جملة، يقرأها، ثم يضغط المايك ليكمل — فيفقد كلامه الأول بلا إنذار.

/// يضمّ [addition] إلى [existing] بفاصل مناسب.
///
/// القواعد:
/// - الحقل فارغ ⇒ النصّ الجديد وحده.
/// - ينتهي بعلامة ترقيم (. ؟ ! ،) ⇒ مسافة واحدة.
/// - ينتهي بمسافة أصلاً ⇒ لا تُضاعف.
/// - غير ذلك ⇒ مسافة فاصلة.
String appendVoiceText(String existing, String addition) {
  final add = addition.trim();
  if (add.isEmpty) return existing;

  final base = existing.trimRight();
  if (base.isEmpty) return add;

  return "$base $add";
}
