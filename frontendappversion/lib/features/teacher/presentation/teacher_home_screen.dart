// ==========================================
// 👨‍🏫 بيتُ المعلّم
// ==========================================
// 🎨 **تصميم Figma** — `design/09-teacher`: ليس في ملفّ المصمّم شاشةُ بوابةٍ
//    للمعلّم إطلاقاً. قسمُه كلُّه **شاشةٌ واحدة**: «مساعد المعلم الذكي» —
//    وهي شاشةُ المحادثة نفسُها، فوقها شريطُ أدواتٍ يبدّل الأداة بلمسة،
//    وتحته بطاقةُ إعداداتِ الأداة المفتوحة.
//
// 🔄 **وما كان قبلها:** بوابةٌ فيها أربعُ بطاقاتٍ كبيرة (خطة · تبسيط · واجب
//    · اسأل) كلٌّ منها تفتح الشات في أداةٍ واحدة، فلا تتبدّل الأداةُ إلا
//    برجوعٍ وفتحٍ جديد. حُذفت البوابةُ ولم يُفقد منها زرّ:
//
//    | ما كان في البوابة | أين صار |
//    |---|---|
//    | بطاقاتُ الأدوات الأربع | **شريطُ الأدوات** فوق المحادثة |
//    | صورةُ المعلّم واسمُه وصفُّه | صفُّ الحساب في **الدرج** ← الإعدادات |
//    | 💾 المحفوظات · 🔔 الإشعارات · ⚙️ الإعدادات | صفوفُ الدرج 🆕 |
//    | 🎏 بانرُ قسم المعلم | الدرج، تحت صفوفه |
//    | 💡 تلميحُ أول زيارة | تلميحُ شاشة المحادثة (`teacher_chat`) |
//
// 🎭 **ويبقى الاسمُ `TeacherHomeScreen`** لأنه عقدُ [RoleHome] وموجّهِ
//    الإشعارات: من اختار «معلّم» يفتح التطبيق هنا ولا يرى شيئاً من واجهة
//    الطالب — لا إحصائيات ولا اختبارات ولا منح.
class TeacherHomeScreen extends StatelessWidget {
  const TeacherHomeScreen({super.key, this.isHome = false});

  /// أهي **الشاشة الأولى** للمعلّم؟ (فلا شيءَ تحتها يُرجَع إليه)
  final bool isHome;

  @override
  Widget build(BuildContext context) => MainChatScreen(
        // 🤖 «اسأل المساعد» هي حالةُ البداية في التصميم (الإطار ٢):
        //    لا شريحةَ مختارة ولا بطاقةَ إعدادات — محادثةٌ مفتوحة.
        teacherTool: TeacherTool.ask,
        isTeacherHome: isHome,
        // 💡 دليلُ «اسأل المساعد» عند أول فتحٍ للتطبيق — ودليلُ كل أداةٍ
        //    أخرى عند أول لمسةٍ لشريحتها (في [MainChatScreen]).
        showDrawerHelp: true,
      );
}
