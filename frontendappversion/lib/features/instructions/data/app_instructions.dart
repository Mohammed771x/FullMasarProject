⚙️ ثم افتح «إعدادات الجلسة» من الزرّ أعلى المحادثة، وأمامك طريقان:

📗 **وضع الدروس:** اختر الوحدة ثم الدرس — ويُرسل الدرس كاملاً.
📄 **وضع الوحدات:** اختر الوحدة، ثم «صفحة» ومرّر شريط الصفحات واضغط
   الأرقام التي تريدها (حتى ٣ صفحات)، أو «برومت» واكتب الموضوع بنفسك.""";

  /// ذيلُ كل دليل — أدواتٌ موجودةٌ في كل وضعٍ وكل مادة.
