  /// مقدّمةُ كل دليل: المادة والصف، ثم سطرٌ يقول ما يفعله القسم فيها.
  static String _header(String subject, int grade, Track track) {
    final scope = Curriculum.hasTracks(grade)
        ? "${Curriculum.gradeLabel(grade)} — ${Curriculum.normalizeTrack(grade, track).label}"
        : Curriculum.gradeLabel(grade);
    return "📚 مرحباً بك في قسم ${_g(subject).title}\n🎓 $scope";
  }

