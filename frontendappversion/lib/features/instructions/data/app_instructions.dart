💡 ويمكنك فتح هذا الدليل في أي وقتٍ من أيقونة المصباح أعلى الشاشة.""";

  /// يبني نصَّ المادة كاملاً — **بالأوضاع المتاحة لهذا الصف وحده**.
  static String _compose(String subject, int grade, Track track) {
    final g = _g(subject);
    final modes = Curriculum.modesFor(subject, grade: grade);
    final parts = <String>[_header(subject, grade, track), g.lead];

    if (g.method.isNotEmpty) parts.add("🎯 **طريقةٌ مقترحة للمذاكرة:**\n${g.method}");

    parts.add("📖 **كيفية الاستخدام:**");

    // 🧮 الرياضياتُ آلةُ حالةٍ أخرى: فرعٌ ← درسٌ ← وضع. فلا يُوصف لها ما
    //    لا تملكه (وحدات · صفحات · مستوى تلخيص).
    if (subject == "رياضيات") {
      parts.add(_mathBody(grade));
    } else {
      parts.add("🔹 **وضع الشرح:**\n$_pickContent\n${g.explain}");
      if (modes.contains("تلخيص")) parts.add("🔹 **وضع التلخيص:**\n${g.summarize}");
      parts.add("🔹 **وضع السؤال:**\n${g.ask}");
      if (modes.contains("وزاري")) parts.add("🔹 **وضع الوزاري:**\n${g.exam}");
    }

    parts.add("""🔹 **وضع الاختبارات:**
🧪 يفتح شاشة «اختبر نفسك»: اختر حتى ثلاثة دروس وعدد الأسئلة، ويُصحَّح لك
فور انتهائه. ونتيجتُك تدخل «تحليل مستواي» فيعرف أضعفَ دروسك ويقترح مراجعتها.""");

    final note = g.notes[grade];
    if (note != null && note.isNotEmpty) parts.add("📌 **خاصٌّ بصفّك:**\n$note");

    parts.add(_footer);
    return parts.join("\n\n");
  }

