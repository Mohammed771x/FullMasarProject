// 🔴 **طلبُ المالك (٢٠٢٦-٠٩-٢٢):** «ادخل في دليل استخدام تطبيق مسار على كل
//    درس في كل الأماكن، وحوّر الكلام على ما يتناسب مع القسم — المعلم وقسم
//    التعليم. في كل مكان، الصف الأول… ولا تخليه يقول قيد الإعداد، ضبطه كامل.»
//
// 🐞 **وما كان قبله:** النصوصُ **قوائمُ مكتوبةٌ بأعيانها لستّ مواد**
//    (احياء · فيزياء · كيمياء · رياضيات · عربي · انجليزي) — ومناهجُ الصفوف
//    الثلاثة فيها **أربعَ عشرةَ مادة**. فمن فتح الدليل في «تاريخ» أو
//    «جغرافيا» أو «فلسفة» أو «منطق» أو «مجتمع» أو «علم الاجتماع» أو «علم
//    الاقتصاد» أو «مبادئ علم الخرائط» رأى: «تعليمات هذه المادة قيد الإعداد 🚧».
//    ثمانيةٌ من أربعَ عشرة — أكثرُ من نصف موادّ الأدبي.
//
// 🎓 **وأسوأُ منه أن المكتوبَ كان لصفٍّ واحد:** النصوصُ تسمّي وحدات الثالث
//    الثانوي وأرقامَ صفحاته («الوحدات الست الأولى» · «من ١٦٢ إلى ١٧٦») وتشرح
//    **وضع الوزاري** — وتُعرض كما هي لطالب الأول الثانوي الذي لا وزاريَّ في
//    صفّه أصلاً ([Curriculum.modesFor]).
//
// ✅ **فصار النصُّ يُركَّب لا يُنسخ:**
//    ① هيكلٌ واحد يشرح **الأوضاعَ المتاحة لهذا الصف وحده** — فلا يَعِد
//       طالبَ الأول بوضعٍ لا يجده، ولا يُنقص طالبَ الثالث شيئاً.
//    ② ولكل مادةٍ **لغتُها**: أمثلتُها من منهجها، وطريقةُ مذاكرةٍ تناسبها
//       (الرياضياتُ فروعٌ، والإنجليزيُّ قواعدُ ومفردات، والتاريخُ تسلسلٌ…).
//    ③ وملاحظاتٌ **لصفٍّ بعينه** حين تكون ثمّة حقيقةٌ تخصّه وحده.
//
// ⚠️ **ولا تُكتب هنا وعودٌ لا يفي بها التطبيق.** ما في هذا الملف يُقرأ على
//    أنه عقد: إن قال «اضغط زرّ اشرح لي» فالزرّ موجودٌ بهذا الاسم، وإن قال
//    «حتى ثلاث صفحات» فذاك سقفُ الخادم نفسُه.
