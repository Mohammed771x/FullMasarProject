        : "";
    return """1️⃣ اختر **الفرع** (تفاضل · تكامل · جبر · هندسة · احتمالات)
2️⃣ ثم اختر **الدرس** من القائمة
3️⃣ ثم اختر الوضع:

🔹 **وضع الشرح:**
📖 اضغط «اشرح لي» فيُشرح الدرس بالتفصيل مع أمثلةٍ محلولة.
💬 وبعد الشرح اسأل عن أي خطوةٍ لم تفهمها — والمحادثة متّصلة.

🔹 **وضع السؤال:**
✏️ اكتب مسألتك في خانة الرسالة فتُحلّ بالخطوات.
📷 أو صوّر المسألة من كتابك وأرسل الصورة.$exam

⏳ **وتحلّى بقليلٍ من الصبر في الرياضيات:** الحلُّ يُراجَع قبل عرضه كي لا
يصلك جوابٌ فيه خطأٌ حسابي.""";
  }

