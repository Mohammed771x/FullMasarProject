import 'package:flutter/widgets.dart';

// ==========================================
// 📌 «الالتصاق بالأسفل» — التمرير أثناء البثّ
// ==========================================
// 🔴 **المشكلة بالضبط (قرار المالك):** الرد يُكتب حرفاً حرفاً، فإن أجبرنا
//    التمرير للأسفل مع كل جزء **سُحبت الشاشة من تحت الطالب** وهو يقرأ.
//    يعود لأعلى ليراجع فقرةً فتقفز به الشاشة إلى الأسفل بعد جزء من الثانية.
//    وهذا يجعل قراءة إجابةٍ طويلة أثناء كتابتها مستحيلة.
//
// ⭐ **القاعدة المطلوبة، حرفياً:**
//    • الطالب **في الأسفل** ⇒ الشاشة تتبع البثّ فيبقى السطر الجديد مرئياً.
//    • الطالب **صعد ليقرأ** ⇒ **لا تتحرك الشاشة إطلاقاً**. النصّ يُكتب في
//      الأسفل وهو يقرأ في الأعلى بهدوء، ويعود متى شاء.
//
// 🧲 **والعودة تلقائية:** ما إن يمرّر بنفسه إلى القاع حتى يستأنف الالتصاق —
//    بلا زرٍّ ولا إعداد. الطالب لا «يُفعّل» شيئاً، بل موضعه هو الإشارة.
//
// 📏 **لماذا عتبةٌ لا مساواة تامة؟** `maxScrollExtent` يتغيّر مع كل حرفٍ
//    يُضاف، والتمرير السلس يصل قريباً من القاع لا عليه تماماً. فمقارنةُ
//    `pixels == max` تكون خاطئة دائماً أثناء البثّ، والالتصاق لا يبدأ أبداً.
class StickToBottom {
  StickToBottom({this.threshold = 80.0});

  /// المسافة (بالبكسل المنطقي) التي يُعتبر ما دونها «في الأسفل».
  ///
  /// ⚠️ ٨٠ ≈ ارتفاع سطرين: أصغرُ منها يفكّ الالتصاق مع كل ارتجاجةِ تمرير،
  ///    وأكبرُ منها يجعل الشاشة تقفز على طالبٍ صعد فعلاً ليقرأ.
  final double threshold;

  bool _stuck = true;
  bool _dragging = false;

  /// هل نتبع الأسفل الآن؟
  bool get isStuck => _stuck;

  /// هل إصبع الطالب على الشاشة الآن؟
  ///
  /// 🔴 **العطل الذي أوجب هذه الحالة:** الطالب يحاول الصعود أثناء البثّ،
  ///    فيسحب عشرين بكسلاً — وهي **أقلّ من العتبة** فيبقى الالتصاق قائماً،
  ///    ثم تصل الدفعة التالية بعد ٥٠ملّي فيقفز `jumpTo` ويعيده إلى القاع.
  ///    فيتكرّر: كل سحبةٍ يبتلعها قفزٌ قبل أن تبلغ العتبة — **ولا يستطيع
  ///    الهروب أبداً**. وهذا حرفياً ما اشتكى منه المالك: «أبغى أطلع لفوق
  ///    بوقف».
  ///
  /// ✅ والعلاج ليس تصغير العتبة (فتنفكّ مع كل ارتجاجة) بل **ألّا نلمس
  ///    القائمة والإصبع عليها**. الطالب يملك الشاشة ما دام يلمسها.
  bool get isDragging => _dragging;

  /// المسافة المتبقية حتى القاع.
  ///
  /// ⚠️ **أرقامٌ خام لا `ScrollPosition`**: القاعدة منطقٌ خالص، وربطُها
  ///    بأصنافِ تمرير فلاتر كان يعني بناء موضعٍ وهميٍّ كاملٍ لاختبار
  ///    مقارنةِ عددين — أي اختباراً يقيس السقالة لا القاعدة.
  static double distanceToBottom(double pixels, double maxExtent) =>
      (maxExtent - pixels).clamp(0.0, double.infinity);

  static bool isAtBottom(double pixels, double maxExtent, double threshold) =>
      distanceToBottom(pixels, maxExtent) <= threshold;

  /// يُحدَّث عند **تمرير الطالب بنفسه** لا عند تحرّك المحتوى.
  ///
  /// ⚠️ التفريق جوهري: نموّ النص أثناء البثّ يزيد `maxScrollExtent` فتكبر
  ///    المسافة إلى القاع بلا أن يلمس الطالب شيئاً. ولو حسبنا ذلك «صعوداً»
  ///    لفكّ الالتصاق **من تلقاء نفسه في أول جزء** — أي أن الميزة تتعطّل
  ///    بالضبط حين تلزم.
  void update({required double pixels, required double maxExtent}) {
    _stuck = isAtBottom(pixels, maxExtent, threshold);
  }

  /// نسخةٌ مريحة لطبقة الويدجت.
  void onUserScroll(ScrollMetrics m) =>
      update(pixels: m.pixels, maxExtent: m.maxScrollExtent);

  /// 👆 نزل الإصبع: الطالب أخذ زمام الشاشة.
  ///
  /// ⚠️ **يفكّ الالتصاق فوراً بلا انتظار عتبة**: العتبة تقيس «أين هو»، وهذه
  ///    تقيس «ماذا يريد». ونيّتُه معروفة لحظة يلمس — أما موضعه فلا يتغيّر
  ///    إلا بعد أن يسحب، وحتى ذلك الحين يكون القفز قد أعاده.
  void beginUserDrag() {
    _dragging = true;
    _stuck = false;
  }

  /// ✋ رُفع الإصبع واستقرّت اللفّة: نُعيد الحكم من **موضعه النهائي**.
  ///
  /// ⭐ فمن عاد إلى القاع بنفسه يستأنف الالتصاق تلقائياً، ومن بقي في الأعلى
  ///    يبقى حيث هو.
  void endUserDrag(ScrollMetrics m) {
    _dragging = false;
    onUserScroll(m);
  }

  /// يُعيد الالتصاق — **بطلبٍ صريح من الطالب وحده**: زرّ «انزل للأسفل».
  ///
  /// ⛔ ولا يُنادى عند الإرسال. كان ذلك سلوكَنا بحجّة أن «من كتب سؤالاً
  ///    يريد أن يرى جوابه» — وردّه المالك (2026-09-09): من يقرأ فقرةً في
  ///    الأعلى ثم يكتب سؤالاً لا يريد أن تُسحب الصفحة من تحت عينه. فالقراءة
  ///    نيّةٌ قائمة، والإرسال لا يلغيها.
  void stick() => _stuck = true;

  void release() => _stuck = false;
}

/// ملحقٌ يُبقي القرار في مكانٍ واحد بدل شروطٍ متناثرة في الويدجت.
extension StickToBottomScroll on ScrollController {
  /// ينزل للقاع **إن كان مسموحاً**، ويعيد هل نزل فعلاً.
  ///
  /// [animated] = `false` أثناء البثّ: الحركة المتحرّكة مع كل جزء تُنتج
  /// اهتزازاً مستمراً لأن كل أنيميشن يُلغي سابقه قبل أن ينتهي.
  bool followBottom(StickToBottom stick, {bool animated = false}) {
    // 👆 **لا نلمس القائمة والإصبع عليها** — راجع [StickToBottom.isDragging].
    if (stick.isDragging || !stick.isStuck || !hasClients) return false;
    final target = position.maxScrollExtent;
    if (animated) {
      animateTo(target,
          duration: const Duration(milliseconds: 260), curve: Curves.easeOutCubic);
    } else {
      jumpTo(target);
    }
    return true;
  }
}
