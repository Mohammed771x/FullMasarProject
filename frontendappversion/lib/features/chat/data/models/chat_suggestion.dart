// ==========================================
// 💡 اقتراحُ بدايةٍ أو متابعةٍ يُعرض للطالب
// ==========================================
// ⚖️ **قرار المالك (2026-09-16):** «اقتراحات مناسبة لكل وضع. وركّز في زرّ
//    اشرح لي — خلّه باين أفضل، لما يضغط عليه يشرح له على طول من المخزون.»
//
// 🎯 والاقتراحُ ثلاثةُ أشياء لا واحد:
//    • `label` ما يراه الطالب — قصيرٌ يُقرأ بلمحة.
//    • `text`  ما يذهب للخادم — جملةٌ كاملةٌ يفهمها البرومبت.
//      (والفصلُ بينهما مقصود: «مثال من الحياة» تُرسل «أعطني مثالاً من
//       الحياة اليومية يوضّح الفكرة» — فالشريحةُ تختصر على العين لا على الموديل.)
//    • `send` أيُرسل فوراً أم **يملأ حقلَ الكتابة**؟
//
// ⚠️ **ولماذا يوجد `send: false` أصلاً؟** لأن وضع السؤال يشترط أن يكتب
//    الطالبُ سؤاله ([ChatController.questionNeedsTypedText] — قرارُ المالك
//    2026-09-14). فاقتراحاتُ ذلك الوضع **قوالبُ ناقصة** («عرّف لي …») تُملأ
//    في الحقل ليُكملها بموضوعه — لا تُرسل ناقصةً فتُهدر من حصّته.
class ChatSuggestion {
  /// النصُّ المعروض على الشريحة.
  final String label;

  /// النصُّ المُرسَل (أو المكتوب في الحقل) — جملةٌ كاملةٌ للموديل.
  final String text;

  /// `true` يُرسل فوراً · `false` يملأ حقلَ الكتابة لِيُكمله الطالب.
  final bool send;

  /// ⭐ الزرُّ البارز — واحدٌ على الأكثر في كل وضع.
  final bool primary;

  const ChatSuggestion(this.label, this.text,
      {this.send = true, this.primary = false});
}
