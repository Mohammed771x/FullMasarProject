"""ⁿلᵣ التباديل والتوافيق — وخطرُهما في أن «ل» و«ق» حرفا كلام.

🔴 هذا الملفّ أخطرُ من إخوته: تعميمُ التحويل يُتلف «ق_ج» في الفيزياء
   (٨٥ موضعاً) و«ق س» و«ق ص» (٤٨) و«س² لو س» و«|ن ق١|».
   فكلُّ اختبارٍ هنا نصفُه إثباتُ الرسم ونصفُه إثباتُ الامتناع.
"""

import pytest

from core.counting import to_counting
from subjects.common import strip_stray_latex


# ══════════════════════════════════════════════════
# ✅ الصيغ الأربع التي يكتبها الكتاب
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src,want,subject", [
    # ١) صيغة الدالّة — كتاب الرياضيات
    ("ل(ن، ر) = ن × (ن-1)", r"\perm{ن}{ر} = ن × (ن-1)", "رياضيات"),
    ("ل(٤، ٣) = ٢٤", r"\perm{٤}{٣} = ٢٤", "رياضيات"),
    ("ل(ن-2، 3)", r"\perm{ن-2}{3}", "رياضيات"),
    # ٢) الأُسّ والحرف المنخفض — كتاب المنطق
    ("أ) ^6 ل_6 = [  ]", r"أ) \perm{6}{6} = [  ]", "منطق"),
    ("^م ل_م", r"\perm{م}{م}", "منطق"),
    ("^20 ق_{2س-1}", r"\comb{20}{2س-1}", "منطق"),
    # ٣) المقوّسة — مفكوك ذات الحدين
    ("(ن ق 0) س^ن", r"\comb{ن}{0} س^ن", "رياضيات"),
    ("(9 ل 3) / (8 ل 2)", r"\perm{9}{3} / \perm{8}{2}", "منطق"),
    # ٤) العارية
    ("أ) 6 ل 2 = [ ]", r"أ) \perm{6}{2} = [ ]", "منطق"),
    ("ن+٢ ق ر", r"\comb{ن+٢}{ر}", "رياضيات"),
])
def test_the_four_book_forms(src, want, subject):
    assert to_counting(src, subject) == want


def test_binary_plus_does_not_get_swallowed():
    """🔴 «٩ ق ر + ٩ ق (ر-١)» — الجمعُ الثنائيّ ليس جزءاً من المقدار.

    خرجت أوّلَ مرّة `\\comb{9}{ر + 9}` فابتلعت المطابقةَ التالية معها.
    الفارقُ أن الكتاب يكتب المركّب **بلا فراغ** («ن+٢») والجمعَ بفراغ.
    """
    out = to_counting("ج) 9 ق ر + 9 ق (ر-1) = 10 ق ر", "منطق")
    assert out == r"ج) \comb{9}{ر} + \comb{9}{ر-1} = \comb{10}{ر}"


# ══════════════════════════════════════════════════
# ⛔ وما لا يجوز أن يُمسّ — كلُّ سطرٍ من بيانات المنهج
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src,subject", [
    ("ق_ج = ك . د", "فيزياء"),                       # قوة الجاذبية — ٨٥ موضعاً
    ("وحيث أن ق_ج = و", "فيزياء"),
    ("مسقطيها ق س و ق ص", "فيزياء"),                 # مركّبتا القوة — ٤٨
    ("المتجهان ق1 وق2 يبدآن من نفس النقطة", "فيزياء"),
    ("= ١/٢ س² لو س - ١/٢ ∫ س . د س", "رياضيات"),     # اللوغاريتم
    ("|ن ق١| + |ن ق٢| = طولاً ثابتاً (٢أ)", "رياضيات"),  # بؤرتا القطع الناقص
    ("فلسفة العصر الوسيط تبدأ من ق ٩م", "فلسفة"),
    ("أوجد قيمة ل إذا كان: العدد كبير", "رياضيات"),
    ("يقال أن المستقيم ل محور تماثل للشكل", "رياضيات"),
])
def test_prose_and_other_symbols_are_untouched(src, subject):
    assert to_counting(src, subject) == src


@pytest.mark.parametrize("subject", ["فيزياء", "كيمياء", "احياء", "عربي",
                                     "انجليزي", "تاريخ", "جغرافيا", "فلسفة"])
def test_only_algebra_and_logic_are_in_scope(subject):
    """⚖️ المادة هي الحدُّ الأول — والفيزياء خارجها عمداً بسبب «ق_ج»."""
    src = "ل(ن، ر) و (ن ق ر)"
    assert to_counting(src, subject) == src


def test_the_live_path_draws_counting():
    """🔴 المنفذ الواحد: ما يمرّ بمسار الدروس يمرّ بالمعالجات القديمة."""
    out = strip_stray_latex("قانون التباديل: ل(ن، ر) = مضروب ن / مضروب (ن-ر)",
                            "رياضيات")
    assert r"\perm{ن}{ر}" in out
    assert r"\fact{ن}" in out
    assert "ل(" not in out
