"""√ الجذر يُرسم لا يُكتب كلمةً — وحدُّ نطاقه أهمُّ من التحويل نفسه.

🔴 **طلب المالك (2026-09-10):** «ليش تكتبه *الجذر*؟ اكتب جذر يعني ارسمه…
   جذر حق اللغة العربية، من اليمين لليسار».

🔴🔴 **وأخطر ما فيه:** مسحُ كل بيانات المنهج كشف أن «جذر» ليست رياضيّةً
     دائماً — **١١٦ موضعاً في الأحياء** جذرُ النبات («جذر وتدي» · «امتصاص
     الماء في الجذر»)، و**أكثرُ رموز «√» علاماتُ صحّ** («ضع العلامة ( √ )»).
     فالتحويل الأعمى يقلب دروس الأحياء والتاريخ إلى طلاسم.
"""
import pytest

from core.roots import ROOT_SUBJECTS, to_sqrt
from subjects.common import strip_stray_latex


# ══════════════════════════════════════════════════
# ✅ ما يجب أن يُرسم
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src,want", [
    ("جذر(٧)", r"\sqrt{٧}"),
    ("جـ = جذر(٧)", r"جـ = \sqrt{٧}"),
    ("جذر ٢", r"\sqrt{٢}"),
    ("جذر س", r"\sqrt{س}"),
    ("√٢٥", r"\sqrt{٢٥}"),
])
def test_roots_become_drawable(src, want):
    assert to_sqrt(src, "رياضيات") == want


def test_named_square_root_in_physics():
    """«ع = الجذر التربيعي ( 196 ) = 14 م/ث» — صيغةُ كتاب الفيزياء."""
    out = to_sqrt("ع = الجذر التربيعي ( 196 ) = 14", "فيزياء")
    assert r"\sqrt{" in out and "التربيعي" not in out


def test_cube_root_keeps_its_index():
    """∛ لها دليلٌ يجب ألّا يضيع، وإلا صار التكعيبيّ تربيعياً — **خطأٌ
    في القيمة** لا في الشكل."""
    assert to_sqrt("الجذر التكعيبي (٨)", "رياضيات") == r"\sqrt[3]{٨}"


def test_nested_expression_is_kept_whole():
    out = to_sqrt("جذر( (س-أ)² + ص² )", "رياضيات")
    assert out.startswith(r"\sqrt{") and "(س-أ)²" in out


# ══════════════════════════════════════════════════
# ⛔ وما **لا** يجوز أن يُمسّ — وهو الأهمّ
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src", [
    "جذر وتدي وجذر ليفي",
    "امتصاص الماء والأملاح من التربة إلى الجذر",
    "رسم تخطيطي لقطاع عرضي في الجذر",
    "ضع العلامة ( √ ) على رمز الإجابة الصحيحة",
])
def test_biology_roots_are_plants_not_radicals(src):
    """🔴 ١١٦ موضعاً. وتحويلها يجعل درس النبات طلاسمَ رياضية."""
    assert to_sqrt(src, "احياء") == src


def test_checkmark_is_untouched_even_in_maths():
    """⚠️ الحدّ الثاني: حتى داخل المادة الرياضية، «( √ )» بلا مقدارٍ بعدها
    علامةُ صحّ لا جذر."""
    src = "ضع العلامة ( √ ) أمام العبارة الصحيحة"
    assert to_sqrt(src, "رياضيات") == src


def test_history_and_arabic_are_out_of_scope_entirely():
    for subj in ("تاريخ", "عربي", "احياء", "جغرافيا"):
        assert subj not in ROOT_SUBJECTS
        assert to_sqrt("جذر ٢", subj) == "جذر ٢"


def test_unknown_subject_changes_nothing():
    """🛡️ الغياب لا يعني الإذن: بلا مادةٍ معروفة لا نحوّل شيئاً."""
    assert to_sqrt("جذر(٧)") == "جذر(٧)"


