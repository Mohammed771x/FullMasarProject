# 🔴 عيبان كشفهما الجهاز — لا الاختبارات
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src", [
    "أحد جذري معادلة تربيعية معاملاتها حقيقية",
    "مجموع الجذرين = -٢",
    "جذرها هو المرافق",
    "جذور الأعداد المركبة بالصورة القطبية",
])
def test_arabic_words_starting_with_root_are_not_torn_apart(src):
    """🔴 **رُصد في المحاكي (2026-09-10):** «أحد جذري معادلة» خرجت
    «أحد √ي معادلة» — كلمةٌ عربية مُزّقت نصفين على شاشة الطالب.

    ⚖️ فحرفٌ عربيّ بعد «جذر» يعني كلمةً أخرى، لا جذراً.
    """
    assert to_sqrt(src, "رياضيات") == src


def test_a_bare_arabic_pronoun_is_not_a_radicand():
    """⚠️ «ي» ضميرٌ لا مقدار. فالمقادير قائمةٌ مغلقة كقائمة الوحدات."""
    assert to_sqrt("جذر ي", "رياضيات") == "جذر ي"


def test_sqrt_markup_reaches_the_renderer_intact():
    """🔴 **رُصد في المحاكي:** جدولُ الاستبدال كان يحوّل `\\sqrt` إلى «√»
    فتبقى الأقواس عاريةً: «√{٣}» على الشاشة.

    ⚖️ والرسّام يفهم `\\sqrt` ويرسم العلامة والسقف معاً — فمن يترجمها
       قبله يُتلفها.
    """
    out = strip_stray_latex("جـ = جذر(٣)", "رياضيات")
    assert out == r"جـ = \sqrt{٣}"
    assert "√{" not in out
