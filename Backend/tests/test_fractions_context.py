# ══════════════════════════════════════════════════
# ⚗️ الكيمياء
# ══════════════════════════════════════════════════

@pytest.mark.parametrize("src", [
    "CH3-CH2-OH --[Cu / 200-300 م]--> CH3-CHO + H2",
    "CH3-CH(OH)-CH3 --[Cu / 200-300 م]--> CH3-CO-CH3 + H2",
    "R-CH2-OH + [O] --[KMnO4 / OH-]--> [R-C(OH)2-H] --(-H2O)--> R-CHO",
    "CH4 + H2O --725م/Ni/Al2O3--> CO + 3H2↑",
])
def test_reaction_conditions_are_never_fractions(src):
    """🔴 الشرطة فوق السهم تعني «مع» لا «على»."""
    assert to_frac(src) == src


def test_cell_notation_survives():
    """⛓️ «//» قنطرةٌ ملحية في الخلية الجلفانية — ولا شرطة فيها قسمة."""
    src = "Fe / Fe3+ // 3Ag+ / 3Ag"
    assert to_frac(src) == src


def test_oxide_and_chloride_formulas_are_a_pair_not_a_ratio():
    """🧪 صفُّ «صيغ الأكاسيد والكلوريدات» في الجدول الدوري: هذه **أو** تلك."""
    assert to_frac("R2O / RCl") == "R2O / RCl"
    assert to_frac("RO / RCl2") == "RO / RCl2"


