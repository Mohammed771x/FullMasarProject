# 📅 التاريخُ ليس كسراً — وعلامةُ الاستفهام ليست مقاماً
# ══════════════════════════════════════════════════
#
# 🔴 كشفهما بناءُ شروح الدروس (2026-09-15) لا مسحٌ مقصود:
#   ① درسُ «الوحدة اليمنية» أخرج `\frac{٢٨}\frac{١٠}{١٩٧٢م}` — **ترميزاً
#      مشوّهاً لا يرسمه التطبيق أصلاً**، ثمانيةَ عشرَ مرّةً في درسٍ واحد.
#      والحارسُ القائم كان يشترط هجرياً مقابل ميلادي، فلا يرى تاريخاً
#      ميلادياً صرفاً. وكتبُ التاريخ والجغرافيا مملوءةٌ بالتواريخ.
#   ② وكتابُ الأحياء كتب «س / ما هي أنواع الصخور ؟» — و«س» اختصارُ
#      **سؤال** — فخرجت `\frac{س}{ما}`: كسرٌ بسطُه «س» ومقامُه «ما».

from core.fractions import to_frac as _f


@pytest.mark.parametrize("src", [
    "اتفاقية القاهرة ٢٨/١٠/١٩٧٢م",
    "بيان طرابلس ٢٨/١١/١٩٧٢م",
    "وقّعت في ١٠/١٩٧٢م",
    "٢٢/٥/١٩٩٠م يوم الوحدة",
    "١٤٤٥هـ",
    "٥/١٩٨٠م",
])
def test_a_date_never_becomes_a_fraction(src):
    out = _f(src)
    assert "\\frac" not in out, out


@pytest.mark.parametrize("src, expect", [
    ("١ / ١٨٣٦", "\\frac{١}{١٨٣٦}"),      # نسبةُ كتلة الإلكترون — كسرٌ حقيقي
    ("1 / 1836", "\\frac{1}{1836}"),
    ("٣ / ٤", "\\frac{٣}{٤}"),
])
def test_a_four_digit_denominator_is_still_a_fraction(src, expect):
    """⚠️ ولا يكفي طولُ المقام: «١/١٨٣٦» كسرٌ في الفيزياء. فالعلامةُ الفارقة
    «م» أو «هـ» في المقام، أو سلسلةُ شرطتين «يوم/شهر/سنة»."""
    assert expect in _f(src)


@pytest.mark.parametrize("src", [
    "س / ما هي أنواع الصخور ؟",
    "س / من اكتشف الخلية ؟",
    "ج / هل تتحلل الصخور ؟",
])
def test_an_interrogative_is_never_a_denominator(src):
    assert "\\frac" not in _f(src), _f(src)


def test_the_real_physics_and_economics_fractions_survive_both_guards():
    """⚖️ الحارسان ضيّقان عن عمد: كسورُ «س/نق» و«س/ك» و«ع/جذر ٢» تبقى."""
    for src, part in (("س / نق", "\\frac{س}{نق}"),
                      ("س / ك", "\\frac{س}{ك}"),
                      ("ع / جذر ٢", "\\frac{ع}{جذر ٢}")):
        assert part in _f(src), src


# 📅 **سنتان مجرَّدتان من أربعة أرقام ليستا كسراً** (رُصد 2026-09-16):
