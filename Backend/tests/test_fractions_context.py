def test_arabic_decimal_comma_does_not_split_the_number():
    """🔴 **أخطرها**: الكتاب العربي يكتب الكسر العشري بالفاصلة.

    «37,3000 / 3,1000» كانت تخرج «37,\\frac{3000}{3},1000» — عددان مقطوعان
    وكسرٌ مخترَع بينهما. وفي الفيزياء أخرجت **مقاماً صفراً**:
    «٠,٥٤ / ٠,٠٠٢٧» ⇦ «\\frac{٥٤}{٠}».
    """
    assert to_frac("37,3000 / 3,1000") == r"\frac{37,3000}{3,1000}"
    assert to_frac("٠,٥٤ / ٠,٠٠٢٧") == r"\frac{٠,٥٤}{٠,٠٠٢٧}"


def test_map_scale_keeps_its_thousands():
    """🗺️ «1/100,000» مقياسُ رسم. وقصُّه إلى «1/100» يجعل الخريطة ألفَ ضعف."""
    assert to_frac("1 / 100,000") == r"\frac{1}{100,000}"


def test_comma_between_words_still_breaks_normally():
    """⚠️ والفاصلة بين كلمتين تبقى فاصلَ تعداد لا جزءاً من مقدار."""
    assert to_frac("أ، ب / ج") == r"أ، \frac{ب}{ج}"


