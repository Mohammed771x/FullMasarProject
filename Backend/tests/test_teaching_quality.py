@pytest.mark.parametrize("rule", ["---", "***", "___", "  ----  "])
def test_decorative_rules_are_stripped(rule):
    """يقطع خيطَ الدرس، ونزعُه لا يُفقد الطالبَ حرفاً — ورفضُه يُكلّف نداءً."""
    out = _tidy(f"سطرٌ أوّل\n\n{rule}\n\nسطرٌ ثانٍ")
    assert "---" not in out and "***" not in out and "___" not in out
    assert "سطرٌ أوّل" in out and "سطرٌ ثانٍ" in out


