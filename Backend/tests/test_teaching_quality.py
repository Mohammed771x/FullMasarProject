@pytest.mark.parametrize("mark, why", [
    (TA.BIG_IDEA, "الفكرةُ الكبرى تسبق المصطلح"),
    (TA.WRAP_UP, "خيطُ الدرس يُجمع في آخره"),
    ("تشبيه", "التقريبُ من حياة الطالب"),
])
def test_each_missing_teaching_element_is_named(mark, why):
    """ولا يكفي أن يُرفض: **يُقال ما نقص** ليُعاد التوليدُ مستوفياً."""
    bad = " ؛ ".join(_defects(_summary_answer()))
    assert mark in bad, f"لم يُسمِّ الفحصُ نقصَ: {why}"


