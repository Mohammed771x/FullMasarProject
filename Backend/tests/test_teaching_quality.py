# 📏 ويتجاوز ٢٥٠٠ حرفاً عمداً: عتبةُ «الدرس المفاهيميّ» التي دونها لا
#    يُشترط التشبيه، فلا يُفتعل لقائمةِ تعريفاتٍ قصيرة.
SOURCE = ("الغدة النخامية غدة صماء تقع أسفل الدماغ. تفرز هرمون النمو. "
          "وتنقسم إلى فص أمامي وفص خلفي. ") * 30


def _summary_answer() -> str:
    """**ملخَّصٌ مرتَّبٌ بامتياز** — وهو بالضبط ما رفضه المالك."""
    return ("حيّاك الله — نشرح اليوم الغدة النخامية.\n\n"
            "### تعريف الغدة النخامية\n"
            "الغدة النخامية غدة صماء تقع أسفل الدماغ، وتفرز هرمون النمو.\n\n"
            "### فصوص الغدة\n"
            "تنقسم الغدة إلى فص أمامي وفص خلفي، ولكلٍّ منهما هرموناته.\n\n"
            "### هرمون النمو\n"
            "يفرزه الفص الأمامي، وينظّم نموّ العظام والعضلات في الجسم.\n") * 4


def _teaching_answer() -> str:
    """نفسُ المحتوى، لكنْ **مشروحاً**: فكرةٌ كبرى وتقريبٌ وخيطٌ وخلاصة."""
    return ("حيّاك الله — نشرح اليوم الغدة النخامية.\n\n"
            f"### {TA.BIG_IDEA}\n"
            "الجسم مملكةٌ فيها غددٌ كثيرة، ولا بدّ لها من قائدٍ ينظّم عملها. "
            "هذا الدرس يعرّفك بذلك القائد: الغدة النخامية.\n\n"
            "### تعريف الغدة النخامية\n"
            "الغدة النخامية غدة صماء تقع أسفل الدماغ، وتفرز هرمون النمو.\n\n"
            "🌍 **قرّبها:** تخيّلها مديرَ المدرسة: لا يدرّس بنفسه، لكنه "
            "يوزّع المهامّ على المعلّمين فينتظم العمل كلُّه.\n\n"
            "عرفنا موقعها ووظيفتها — فمِمَّ تتركّب؟\n\n"
            "### فصوص الغدة\n"
            "تنقسم الغدة إلى فص أمامي وفص خلفي، ولكلٍّ منهما هرموناته.\n\n"
            "⚠️ **انتبه:** الفصّ الخلفي **يخزّن** ولا يصنع، والخلطُ بينهما "
            "أكثرُ ما يقع فيه الطالب.\n\n"
            "🧠 **ثبّتها:** الأماميُّ يصنع، والخلفيُّ يحفظ.\n\n"
            "وعرفنا الفصّين — فما أشهرُ ما يفرزانه؟\n\n"
            "### هرمون النمو\n"
            "يفرزه الفص الأمامي، وينظّم نموّ العظام والعضلات في الجسم.\n\n"
            "وبهذا نكون قد مررنا بالدرس كلِّه — فما خلاصتُه؟\n\n"
            f"### {TA.WRAP_UP}\n"
            "بدأنا من غدّةٍ صغيرةٍ أسفل الدماغ، فرأينا أنها تنقسم فصّين، "
            "وأن الأماميَّ منهما يفرز هرمون النمو الذي ينظّم نموّ الجسم — "
            "فمن موقعها الصغير تُدار المملكةُ كلُّها.\n") * 2


def _defects(answer: str, subject: str = "احياء", lesson: str = "الغدة النخامية"):
    return verify(subject, {}, SOURCE, answer, lesson)


