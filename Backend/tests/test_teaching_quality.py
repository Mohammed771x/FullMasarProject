# 🧵 خيطُ الدرس — أقسامٌ موصولةٌ لا جزرٌ مرصوفة
# ══════════════════════════════════════════════════
#
# 🔴 **قِيس (2026-09-16) على ٨١٣ درساً**: جملُ الوصل **٠٫١–٠٫٣ للدرس في
#    كلِّ المواد** رغم أن المواصفة تطلبها في رأس النظام — فقال المالك عن
#    الفيزياء: «شرحٌ خام كذا، بدون السطور». والعلّةُ نفسُها المتكرّرة:
#    **ما يُطلب في رأس النظام يُهمَل، وما يُطلب في رسالة الطالب يُطاع.**

def test_a_bridge_counts_only_when_it_precedes_the_heading():
    """⚖️ **موضعُ الكلمة هو معناها.** أوّلُ صياغةٍ عدّت كلماتِ الوصل في كل
       الشرح، فاجتاز نصٌّ أقسامُه مرصوفةٌ لأن «والآن» وردت في فقرةٍ بعيدة."""
    from tools.build_explanations import _bridged
    joined = ("### أوّل\nنصٌّ.\n\nعرفنا هذا — فكيف ذاك؟\n\n### ثانٍ\nنصٌّ.")
    stranded = ("### أوّل\nوالآن نبدأ هذا القسم.\n\nتعريفٌ جافٌّ بلا وصل.\n\n"
                "### ثانٍ\nنصٌّ.")
    assert _bridged(joined) == 1
    assert _bridged(stranded) == 0


