# π core/symbols.py — رموزٌ تُكتب كلاماً وحقُّها أن تكون رمزاً
# ==================================================
# 🔴 **ما رآه المالك (2026-09-10):** «الرموز مثل باي، حصلت مكتوب بالغلط
#    عربية… خلّه ينكتب باي» — أي الرمز لا حروفَه.
#
# ⚖️ والكتاب نفسه يكتبها رمزاً في الأغلب: **٢٥٩ «π»** في الرياضيات
#    و**٢٦٦** في الفيزياء، مقابل **٢٤** موضعاً بحروف «باي». فالتحويل
#    يوحّد الكتابَ مع نفسه لا يغيّره.
#
# 🔴 **والفخّ اسمُ عَلَم:** «طومان **باي**» سلطانُ المماليك في كتاب
#    التاريخ. ولذلك المادةُ حدٌّ لازم — وحدُّ الكلمة كذلك، فـ«تـباين»
#    و«متـباين» تحوي الحروف الثلاثة (٥٤ موضعاً في الجغرافيا وحدها).
#
# 🔴🔴 **و«ط» أخطرُ منها، ومادةٌ واحدة تقبلها.** قرأتُ المواضعَ واحداً
#      واحداً (2026-09-10) فإذا هي أربعةُ معانٍ لا معنى:
#        • **رياضيات — ٣٩ موضعاً، كلُّها π بلا استثناء**: «جا(ط/٤)» ·
#          «س←ط/٢» · «(٤ ، ٣ط/٢)» في الصورة القطبية.
#        • **فيزياء — ١٦٧**: «ط م» طاقةُ الوضع · «ط ح» · و«سطل (ط)»
#          اسمُ جسمٍ في رسمٍ توضيحيّ!
#        • **كيمياء — ١٥**: «ط = ك × ع²» — الطاقةُ في معادلة أينشتاين.
#        • **منطق — ٢**: «ن، ر ∋ ط» مجموعة. والاقتصاد «م ط» مرونةُ الطلب.
#      فتحويلُها خارج الرياضيات يقلب معادلةَ الطاقة إلى «π = ك × ع²».
#
# ⚠️ **وحدُّ الكلمة يجب أن يشمل التشكيل**: «فِطْرَتَ» في آيةٍ بكتاب
#    التاريخ تبدو «ط» مفردةً لأن الحركات ليست حروفاً — ٣٧ موضعاً وهميّاً.
#
# ⚠️ و«ط» ترتيبٌ أبجديّ للفقرة التاسعة («ط - عناصر الإنتاج»)، فتُستثنى
#    إن تلاها شرطةٌ أو قوسُ ترقيم — لم تقع في الرياضيات بعدُ، وقد تقع.

import re

from .roots import ROOT_SUBJECTS, is_root_subject

__all__ = ["to_symbols", "ROOT_SUBJECTS"]

# حرفٌ عربيّ **أو حركة أو تطويل** — الحدُّ لا يصحّ بدونها.
_ARABIC = r"\u0621-\u064a\u064b-\u0652\u0640"
_PI = re.compile(r"(?<![" + _ARABIC + r"])باي(?![" + _ARABIC + r"])")

# «ط» رمزَ π — في الرياضيات وحدها.
PI_LETTER_SUBJECTS = frozenset({"رياضيات"})
_TA = re.compile(r"(?<![" + _ARABIC + r"])ط(?![" + _ARABIC + r"])")
_LIST_MARKER = re.compile(r"^\s*[-–.)]")


def _ta_sub(m: "re.Match") -> str:
    """«ط» ⇒ «π» ما لم تكن ترقيمَ فقرةٍ أبجدياً."""
    tail = m.string[m.end():m.end() + 3]
    return m.group(0) if _LIST_MARKER.match(tail) else "π"


def to_symbols(text: str, subject: str = "") -> str:
    """«باي» و«ط» ⇒ «π» — كلٌّ في نطاقه.

    ⚖️ «باي» في كل المواد الرياضية (رابطةُ باي في الكيمياء منها)،
       و«ط» في **الرياضيات وحدها** — راجع الشرح أعلاه.
    """
    if not text or not is_root_subject(subject):
        return text
    if "باي" in text:
        text = _PI.sub("π", text)
    if "ط" in text and (subject or "").strip() in PI_LETTER_SUBJECTS:
        text = _TA.sub(_ta_sub, text)
    return text
