"""🖌️ أيُّ المواد لها رسّامُ كسور — ولا تُحوَّل «/» كسراً في غيرها."""

# 🖌️ **رسّامُ الكسور لمواد المعادلات وحدها** (طلب المالك 2026-09-29: «لكل
#    مادة رسام، والتاريخ بلا رسام… خليها بدون رسام وما يكتب كسور»).
#    قِيس قبله: «١٩٥٦/٤/٢١م» في التاريخ ⇐ `\\frac{١٩٥٦}\\frac{٤}{٢١م}`، وتواريخُ
#    الجغرافيا وجداولُها («٢٤٢/٦») كسوراً، و«Must I ...? / Do I» في الإنجليزي.
#    والخرائطُ فيها مقياسُ رسمٍ ونسبُ دوائر حقيقية، والاقتصادُ مرونةٌ بقسمة.
FRACTION_SUBJECTS = frozenset({
    "رياضيات", "فيزياء", "كيمياء", "احياء", "منطق",
    "علم الاقتصاد", "مبادئ علم الخرائط",
})


def uses_fractions(subject) -> bool:
    """هل لهذه المادة رسّامُ كسور؟ — بلا مادةٍ مسمّاة يبقى السلوك القديم."""
    s = (subject or "").strip()
    return not s or s in FRACTION_SUBJECTS
