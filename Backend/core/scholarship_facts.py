def _funding(sch):
    full = sch.get("funding_type") == "full"
    body = (f"**{_head(sch)}** ممولةٌ بالكامل." if full
            else f"**{_head(sch)}** تمويلُها جزئيّ.")
    if sch.get("benefits"):
        body += "\n\n" + _line("وتشمل", sch["benefits"])
    return body + _source_note(sch)


def _dates(sch):
    """المواعيدُ والحالةُ — والحالةُ تُحسب لا تُخزَّن ([scholarships])."""
    lines = []
    if sch.get("open_date"):
        lines.append(f"- فتح التقديم: {sch['open_date']}")
    if sch.get("close_date"):
        lines.append(f"- آخر موعد للتقديم: {sch['close_date']}")
    status = store.STATUS_LABELS.get(sch.get("status", ""), "")
    if status:
        lines.append(f"- الحالة الآن: {status}")
    days = sch.get("days_left")
    if isinstance(days, int) and 0 <= days < 9999 and sch.get("status") == "open":
        lines.append(f"- المتبقّي على الإغلاق: {days} يوماً")
    return (f"مواعيد **{_head(sch)}**:\n\n" + "\n".join(lines)
            + _source_note(sch))


def _about(sch):
    """المقدّمة — وهي **مجموعُ ما يعرّف بالمنحة** لا حقلٌ واحد.

    ⚖️ نصُّ المالك: «لو قال مقدمة عن المنحة تعطيك مقدمة… وهذه الوثائق
       وهذه وهذه» — أي بطاقةٌ تعريفيةٌ مختصرة، لا فقرةُ `about` وحدها.
    """
    head = [f"**{_head(sch)}**"]
    if sch.get("country"):
        head.append(f"- الدولة: {sch.get('flag', '')} {sch['country']}".strip())
    head.append("- التمويل: " + ("ممولة بالكامل"
                                 if sch.get("funding_type") == "full"
                                 else "تمويل جزئي"))
    if sch.get("degree_levels"):
        head.append("- المراحل: " + "، ".join(sch["degree_levels"]))
    if sch.get("min_gpa"):
        head.append(f"- المعدّل المطلوب: {sch['min_gpa']}% فأعلى")
    if sch.get("close_date"):
        head.append(f"- آخر موعد للتقديم: {sch['close_date']}")
    body = "\n".join(head)
    if sch.get("short_desc"):
        body += f"\n\n{sch['short_desc'].strip()}"
    if sch.get("about"):
        body += f"\n\n{sch['about'].strip()}"
    # 🧭 وخاتمةٌ تدلّ على الخطوة التالية بدل أن ينتهي النصُّ فجأة.
    have = [n for n, k in (("الشروط", "requirements"),
                           ("الوثائق المطلوبة", "documents"),
                           ("المزايا", "benefits"),
                           ("خطوات التقديم", "how_to_apply"))
            if sch.get(k)]
    if have:
        body += "\n\nواسألني عن: " + " · ".join(have) + "."
    return body + _source_note(sch)


