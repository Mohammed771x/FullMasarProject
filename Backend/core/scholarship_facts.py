_TASHKEEL = re.compile(r"[ً-ْـ]")
_NON_WORD = re.compile(r"[^\wء-ي\s]", re.U)

# ⚠️ السوابقُ تُنزع بترتيبها الأطولِ أوّلاً: «للتقديم» = لل + تقديم، ولو
#    نُزعت «ل» وحدها لبقي «لتقديم» فلا يطابق شيئاً.
_PREFIXES = ("وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ك", "ل")


def _stem(word: str) -> str:
    for p in _PREFIXES:
        if word.startswith(p) and len(word) - len(p) >= 3:
            return word[len(p):]
    return word


def _words(text: str) -> list:
    """كلماتُ السؤال مطبَّعةً — **بلا تجريدٍ من السوابق**.

    ☢️ **ولماذا لا تُجرَّد هنا؟** لأن المجرِّد أعمى: «وثائق» تبدأ بواو
       فيقطعها فتصير «ثايق»، و«كم» و«لغة» و«فترة» مثلُها. فلو جُرِّدت
       الكلماتُ مرّةً واحدة لاختلف الطرفان في كلِّ كلمةٍ تبدأ بحرفِ سابقة.
       العلاج: تُحفظ الكلمةُ كما هي، **ويُجرَّب الوجهان عند المطابقة**
       ([_matches]) — فـ«الوثائق» تطابق «وثائق» بلا أن تُتلف «وثائق» نفسُها.
    """
    t = _TASHKEEL.sub("", text or "")
    t = (t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
          .replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و")
          .replace("ئ", "ي"))
    t = _NON_WORD.sub(" ", t).lower()
    return [w for w in t.split() if w]


def _matches(word: str, vocab) -> bool:
    """الكلمةُ في المجموعة — بنفسها أو بعد نزع سابقتها."""
    return word in vocab or _stem(word) in vocab


