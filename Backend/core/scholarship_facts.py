# 🔴 والمفرداتُ تمرّ بنفس المطبِّع — لا تُكتب باليد مطبَّعةً
# ══════════════════════════════════════════════════
#
# ☢️ **عطلٌ وقع فعلاً وأمسكه القياس:** كتبتُ «وثائق» في قائمة النيّة، لكن
#    المطبِّع يحوّل «ئ» إلى «ي» فيصير مدخلُ الطالب «وثايق» — فلا يطابق
#    شيئاً، و«ما الوثائق المطلوبة؟» (مثالُ المالك حرفياً) تذهب إلى الموديل.
#    والخطأ ليس في الحرف بل في **أن للمفردات مطبِّعاً وللسؤال مطبِّعاً آخر**.
#    فالعلاج بنيويّ: **مصدرُ تطبيعٍ واحد للطرفين**.

def _vocab(*words) -> frozenset:
    """تُطبَّع المفرداتُ بنفس مسار السؤال — فلا يختلف الجانبان أبداً.

    وتُحفظ الكلمةُ **ومجرَّدُها** معاً، كي تُطابَق مهما كتبها الطالب.
    """
    out = set()
    for w in words:
        for token in _words(w):
            out.add(token)
            out.add(_stem(token))
    return frozenset(out)


