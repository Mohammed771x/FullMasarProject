# ══════════════════════════════════════════════════
#
# 🔴 **علّةُ المالك (2026-09-20):** «تسع نيّات تُجاب من البطاقة، حلو — وين
#    هالنيّات؟ **مش موجودة**. بغيت المواعيد، مش موجود وين مواعيد المنحة.
#    خلّها من ضمن الاقتراحات: لو ضغطها خلاص يطلع له الوثائق، لو ضغطها
#    يجيب له كذا. **لأنه مش باين عندي.**»
#
# ⚖️ وهو محقّ تماماً: بنيتُ تسعةَ أبوابٍ ثم تركتُ الطالبَ يخمّن أسماءها.
#    والاقتراحاتُ كانت **أربعةً مكتوبةً في الكود** لا صلةَ لها بما تملكه
#    المنحة — فيها «كيف أكتب خطاب الدافع؟» (لا تجيبها بطاقة) وليس فيها
#    المزايا ولا التخصصات ولا المراحل.
#
# 🎯 **فالاقتراحُ الآن يُشتقّ من البطاقة نفسِها**: بابٌ لكل نيّةٍ **تملك
#    المنحةُ بياناتها**. منحةٌ بلا تخصصاتٍ لا يظهر لها بابُ التخصصات، فلا
#    يضغط الطالبُ زرّاً يقوده إلى لا شيء.
#
# 🔒 **ومصدرٌ واحد للنصّ**: نصُّ السؤال هنا هو نفسُه الذي يمرّ على
#    [intent_of]. ولو كتبنا الاقتراحَ في التطبيق ونيّتَه هنا لانفصلا يوماً
#    — فضغطةُ زرٍّ تذهب إلى الموديل ويُدفع ثمنُها بلا أن يشتكي أحد.
#    ويحرسه `test_every_suggestion_is_answerable_from_the_card`.

# (النيّة، نصُّ الزرّ، السؤالُ المُرسَل، سؤالٌ بديل حين يغيب الحقلُ الأول)
_SUGGESTIONS = (
    ("requirements", "الشروط",          "ما شروط التقديم؟",      ""),
    ("documents",    "الوثائق المطلوبة", "ما الوثائق المطلوبة؟",  ""),
    ("dates",        "المواعيد",         "متى آخر موعد للتقديم؟", "متى يفتح التقديم؟"),
    ("benefits",     "المزايا",          "ما مزايا المنحة؟",      ""),
    ("apply",        "خطوات التقديم",    "ما خطوات التقديم؟",     ""),
    ("fields",       "التخصصات",         "ما التخصصات المتاحة؟",  ""),
    ("levels",       "المراحل",          "ما المراحل الدراسية؟",  ""),
    ("funding",      "التمويل",          "هل المنحة ممولة بالكامل؟", ""),
    ("about",        "نبذة عن المنحة",   "نبذة عن المنحة",        ""),
)


def suggestions(sch: dict) -> list:
    """أبوابُ هذه المنحة — كلُّ زرٍّ منها يفتح جواباً مخزوناً حتماً.

    ⚠️ **ولا يُعرض بابٌ لا جوابَ خلفه**: يُجرَّب السؤالُ فعلاً على البطاقة
       قبل عرضه. فهذا الفحصُ — لا قائمةُ حقولٍ نتوقّعها — هو ما يضمن أن
       كلَّ ضغطةٍ تُثمر، مهما تغيّرت شروطُ [answer_for] لاحقاً.
    """
    if not isinstance(sch, dict):
        return []
    out = []
    for _, label, question, fallback in _SUGGESTIONS:
        for candidate in (question, fallback):
            if candidate and answer_for(sch, candidate):
                out.append({"label": label, "question": candidate})
                break
    return out


def intent_of(question: str):
    """نيّةُ السؤال إن كان **سؤالَ حقلٍ خالصاً**، وإلا `None`.

    🔴 **والشرطُ الثاني هو الذي يحمي المحادثة**: بعد مطابقة كلمات النيّة
       لا يجوز أن تبقى في السؤال كلمةٌ ذاتُ معنى. فـ«ما الوثائق المطلوبة؟»
       تُسلَّم، و«ما الوثائق المطلوبة لطلاب الهندسة؟» تمضي إلى الموديل —
       لأن «الهندسة» سؤالٌ لا تجيبه قائمةٌ عامة.
    """
    words = _words(question)
    if not words:
        return None
    meaningful = [w for w in words if not _matches(w, _FILLER)]
    if not meaningful:
        return None
    for key, vocab, _, _ in _INTENTS:
        hit = [w for w in meaningful if _matches(w, vocab)]
        if not hit:
            continue
        if any(not _matches(w, vocab) for w in meaningful):
            return None          # ⛔ معه موضوعٌ زائد ⇒ إلى الموديل كاملاً
        return key
    return None


def answer_for(sch: dict, question: str, has_image: bool = False):
    """جوابُ البطاقة إن أمكن — وإلا `None` فيمضي الطلبُ إلى الموديل.

    ⚠️ **والصورةُ تُلغي المخزونَ دائماً**: من أرفق كشفَ درجاتٍ وسأل عن
       الشروط يريد مطابقةً بينهما، لا قائمةً عامة.

    ⚠️ **وحقلٌ فارغٌ يمضي إلى الموديل** ولا يُردّ عليه بـ«غير متوفّر»:
       الموديل يعرف كيف يحوّل الطالبَ إلى الموقع الرسميّ، والردُّ الجافّ
       بابٌ مغلقٌ في وجهه. المخزونُ يخدم ما نملكه، لا غيابَه.
    """
    if has_image or not isinstance(sch, dict):
        return None
    key = intent_of(question)
    if key is None:
        return None
    for name, _, needs, build in _INTENTS:
        if name != key:
            continue
        if not any(sch.get(f) for f in needs):
            return None
        try:
            return build(sch).strip()
        except Exception as e:                  # بناءٌ مساعد لا يُسقط طلباً
            print(f"⚠️ تعذّر بناءُ جواب «{name}» من البطاقة: {e}")
            return None
    return None
