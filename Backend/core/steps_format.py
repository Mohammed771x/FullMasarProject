# 🔴 **ما رآه المالك:** «الخطوات كلها محشوكة… فيه نقطة قبل الكلام وينحسب
#    من ضمن المعادلة، تحصل رقم اثنين كذا». أي أن «٢.» في أول السطر يلتصق
#    بصرياً بالمعادلة التي تليه فتُقرأ «٢ = ٢» — والطالب يحسبها من الحلّ.
#
# ⚖️ **والبرومبت وحده لا يكفي** (نفس درس [core/latex_guard.py]): الموديل
#    يمتثل غالباً لا دائماً، والتباعد أمرٌ **شكليّ بحت** يمكن ضمانه بيقين
#    بعد التوليد بلا أي خطرٍ على المعنى — فهو أولى الأمور بالفلترة.

import re

# ترويسةُ خطوة: «٣)» · «3.» · «**المجال:**» — هذه ما يلتصق بالمعادلة.
_HEAD = re.compile(
    r"^\s*(?:"
    r"[٠-٩0-9]+\s*[.)\-–]\s"
    r"|\*\*[^*\n]{1,60}\*\*\s*:"
    r")",
)

# عنصرُ تعداد: «- » · «▪️ » — أبناءُ الترويسة.
_BULLET = re.compile(r"^\s*[-*•▪️◦]\s")


def space_steps(text: str) -> str:
    """يضمن سطراً فارغاً بين الخطوات — بلا تغيير حرفٍ من المحتوى.

    ⚖️ **والتباعد ليس واحداً للجميع، وإلا بعثر ما هو مجموع:**
       • ترويسةُ خطوة  ⇒ سطرٌ فارغ قبلها دائماً (هي موضع الالتصاق).
       • قائمةٌ متتابعة ⇒ عناصرها **متلاصقة** (هي وحدةٌ واحدة)، ويُفصل
         أوّلها عمّا قبله إلا أن يكون ترويسةً تُقدّمها بنقطتين.

    ⚠️ ولا يلمس ما بين ``` ``` — قد يكون تباعدُه مقصوداً.
    """
    if not text:
        return text

    out: list[str] = []
    in_fence = False
    for line in text.split("\n"):
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence or not line.strip():
            out.append(line)
            continue

        prev = out[-1] if out else ""
        need = False
        if _HEAD.match(line):
            need = bool(prev.strip())
        elif _BULLET.match(line):
            # أوّلُ القائمة يُفصل، إلا بعد ترويسةٍ تُقدّمها («…:»)
            need = bool(prev.strip()) and not _BULLET.match(prev) \
                and not prev.rstrip().endswith(("：", ":"))

        if need:
            out.append("")
        out.append(line)

    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()
