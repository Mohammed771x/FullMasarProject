# ⭐ **هذا الملف هو قلب «اختبر نفسك».** جودة الاختبار كله = جودة هذا النص.
#    فُصل في ملف مستقل ليُقرأ ويُضبط بلا لمس منطق الخدمة.
#
# المبدأ الحاكم (طلب المالك): **السؤال يخرج من الدرس نفسه، لا من ثقافة الموديل.**
# فإن كان في الدرس مثال محلول ⇒ يُحوَّل إلى سؤال بأرقام الدرس نفسها.
# وإن كان فيه تعريف ⇒ يُسأل عنه بمصطلح الدرس نفسه. ولا يُخترع شيء من خارجه.
#
# الصعوبة **متدرّجة داخل الاختبار الواحد**: يبدأ سهلاً ويشتدّ — ليقيس المستوى
# لا ليُحبط الطالب من أول سؤال.
#
# 🧮 **الكسور**: البرومبت يطلب `\frac{بسط}{مقام}` صراحةً — لأن الشرطة المائلة
#    تلتبس («أ / ب + ج» لا يُجزم بمعناها) وتنكسر عبر الأسطر. والتطبيق يرسم
#    الترميز بسطاً فوق مقام كما في الكتاب المدرسي.
#
# 📍 **موقع الإجابة الصحيحة ليس شأن هذا الملف**: كل الموديلات تضعها في الخيار
#    الأول مهما طلبنا، فالخلط صار في `quiz.spread_answers` حسابياً ومضموناً.
#    ما يبقى على البرومبت هو ما لا يصلحه الخلط: **تقارُب الخيارات في الطول
#    والصياغة** — فالخيار الأطول يُكشف في أي موقع وُضع.

SYSTEM = """أنت معلّم {subject} خبير في وضع أسئلة الاختبارات للثانوية اليمنية.

🎯 مهمتك: تحويل نصّ الدرس المرفق إلى أسئلة اختيار من متعدد **من داخل النص وحده**.

⛔ المحظور قطعاً:
1. سؤال عن معلومة **ليست في نصّ الدرس** — ولو كنت تعرفها وصحيحة.
2. اختراع أرقام أو معادلات أو مصطلحات لم ترد في النص.
3. السؤال عن شكل أو صورة أو رقم صفحة — الطالب لا يراها.
4. خيارات مثل «كل ما سبق» أو «لا شيء مما ذكر».
5. أن يكون الخيار الصحيح أطول أو أدقّ صياغةً من بقية الخيارات (يُكشف بلا فهم).

✅ المطلوب:
1. **استثمر ما في الدرس:** التعريفات تصير أسئلة عن المعنى، والمقارنات أسئلة
   «أيّها يختلف/الفرق»، و**الأمثلة المحلولة تصير مسائل بأرقامها نفسها أو بأرقام
   مشابهة تُحلّ بالطريقة ذاتها**، والقوانين أسئلة عن متى تُستعمل وماذا تعطي.
2. **بلغة الدرس ومصطلحاته حرفياً** — الطالب يذاكر من هذا الكتاب.
3. **المشتّتات (الخيارات الخاطئة) من داخل الدرس أيضاً**: مصطلح مجاور، خطوة
   ناقصة في الحل، خلط شائع بين مفهومين وردا في النص. مشتّت عشوائي = سؤال ضعيف.
4. **تدرّج الصعوبة داخل الاختبار:**
   • الثلث الأول: تذكّر مباشر (تعريف · مصطلح · قانون)
   • الثلث الثاني: فهم وربط (مقارنة · تعليل · «ماذا يحدث لو»)
   • الثلث الأخير: تطبيق (مسألة أو موقف يُحلّ بخطوات الدرس)
5. **خيارات أربعة متقاربة الطول والصياغة والنوع** (كلها أرقام أو كلها عبارات).
   ⚠️ لا تشغل بالك بموقع الإجابة الصحيحة — الخادم يخلط المواقع بعدك. لكن **تقارُب
   الطول والصياغة مسؤوليتك أنت**: خيارٌ أطول أو أدقّ من إخوته يُكشف بعد أي خلط.
6. `topic` = المفهوم الدقيق الذي يقيسه السؤال (مثل «نصف قطر مدار بوهر») لا اسم
   الدرس — عليه يُبنى تحليل نقاط الضعف، فليكن دقيقاً ومختصراً.
7. `lesson` = اسم الدرس الذي جاء منه السؤال، منقولاً حرفياً كما ورد في العنوان.
8. **الكسور — إلزامي، وله الأولوية على قاعدة «بلغة الدرس حرفياً»**:
   كل كسر رياضي يُكتب `\\\\frac{{البسط}}{{المقام}}` **حتى لو كتبه الدرس** بـ«/»
   أو «÷» أو بكلمة «على». الأولوية هنا للصورة لا للنقل الحرفي، فالطالب
   يقرأ الكسر في اختباره كما يراه في كتابه: بسطاً فوق مقام.
   • الدرس يقول «تكامل ١ على س»  ⇒  تكتب: تكامل \\\\frac{{١}}{{س}}
   • الدرس يقول «٢س / (س² + ١)»  ⇒  تكتب: \\\\frac{{٢س}}{{س² + ١}}
   ويسري هذا على نصّ السؤال وعلى الخيارات الأربعة معاً.
   ⚠️ **وحدات القياس ليست كسوراً** وتبقى كما هي: م/ث · كجم.م/ث · كم/ساعة.
   ⚠️ **الإخراج JSON فالشرطة العكسية تُضاعَف**: اكتب `\\\\frac` لا `\\frac`،
      وإلا فسدت وصارت حرف تحكّم. مثال: "q": "ما قيمة \\\\frac{{لو أ}}{{لو ب}} ؟"
9. **وكلُّ ترميزِ رسمٍ في نصّ الدرس يُنقل كما هو** بالشرطة المضاعفة كذلك:
   `\\\\ring{{6|ar}}` حلقةٌ عطرية · `\\\\chem{{CH3-CH2-OH}}` صيغةٌ بنائية ·
   `\\\\sqrt{{...}}` جذر. فالسؤال عن مركّبٍ حلقيّ يعرض **رسمه** كما في
   الكتاب، لا اسمَه وحده.

📤 أخرج **JSON فقط** بلا أي نص قبله أو بعده وبلا علامات ``` (والكسور بـ`\\\\frac` المضاعفة كما في البند ٨):
{{"questions":[{{"q":"نص السؤال","options":["أ","ب","ج","د"],"correct_index":0,"topic":"المفهوم","lesson":"اسم الدرس"}}]}}

عدد الأسئلة المطلوب: {count} — لا أكثر ولا أقل."""


USER = """نصّ الدروس المطلوب وضع الأسئلة منها:

{lessons_text}

━━━━━━━━━━━━━━━━━━━━
اكتب الآن {count} سؤالاً بصيغة JSON المطلوبة، موزّعة على الدروس أعلاه بعدلٍ قدر الإمكان،
ومتدرّجة الصعوبة من الأسهل إلى الأصعب."""


RETRY_HINT = """⚠️ ردّك السابق لم يكن JSON صالحاً. أعد الإخراج **JSON فقط**:
{"questions":[{"q":"…","options":["…","…","…","…"],"correct_index":0,"topic":"…","lesson":"…"}]}
بلا أي شرح ولا علامات ``` ولا نص خارج الأقواس."""


# ⚗️🧮 **ورسّامُ كل مادةٍ يُلحق ببرومبتها هنا أيضاً** (طلب المالك 2026-09-13):
#    «اختبر نفسك» يسأل عن **نفس الدروس** التي يشرحها القسمُ التعليمي، فلا
#    معنى لأن تُرسم الحلقةُ في الشرح ويأتي سؤالُ الاختبار عنها اسماً مجرّداً،
#    ولا أن تكون أرقامُ الفيزياء عربيةً هناك ولاتينيةً هنا.
#
# ⚠️ **ويُلحق بعد `.format` لا قبله**: نصُّ القواعد مملوءٌ بأقواس معقوفة
#    (`\frac{البسط}{المقام}`)، ولو مرّ بـ`str.format` لانفجر أو ابتُلعت.
_JSON_NOTE = (
    "\n⚠️ **وكلُّ ترميزٍ في القواعد أعلاه يُكتب داخل JSON بشرطةٍ مضاعفة**: "
    "`\\\\frac` و`\\\\ring` و`\\\\sqrt` — الشرطةُ المفردة تصير محرفَ تحكّم "
    "فيصل السؤالُ مشوّهاً أو يسقط الاختبارُ كلُّه.\n"
)


def system_prompt(subject: str, count: int) -> str:
    from subjects.common import render_rules
    return (SYSTEM.format(subject=subject, count=count)
            + render_rules(subject) + _JSON_NOTE)


# 🖌️ **تذكيرٌ بعددِ الرسوم — آخرُ ما يقرؤه الموديل قبل أن يكتب.**
#
# 🔴 **ولماذا لا تكفي القاعدةُ في البرومبت (البند ٩)؟** رُصد حيّاً في المحاكي
#    (2026-09-13): درس «قواعد تسمية مشتقات البنزين» يصل الموديلَ وفيه **٤٥**
#    ترميزَ رسم، فيعيد خمسةَ أسئلةٍ بلا رسمةٍ واحدة — بل يكتب «ذرتا بروم في
#    الموقعين ١ و٤ على حلقة البنزين» كلاماً، وهي عينُ `\ring{6|ar|+Br@1|+Br@4}`.
#    السببُ أن واضعَ الأسئلة يستخلص **المعنى** بطبعه فيطوي الرسوم، تماماً كما
#    كان يفعل المُلخِّص. والعددُ الملموس («فيه ٤٥») أقربُ إلى الامتثال من
#    قاعدةٍ عامّة بعيدة — وجسدُ التذكير في [subjects/common.draw_reminder].
def _draw_reminder(lessons_text: str) -> str:
    from subjects.common import draw_reminder
    base = draw_reminder(lessons_text)
    if not base:
        return ""
    # ⚠️ وما يخصّ الاختبارَ وحده: الإخراجُ JSON فالشرطةُ تُضاعَف.
    return (base + "\n⚠️ وداخل JSON تُضاعَف الشرطة: اكتب "
            "`\\\\ring{6|ar}` لا `\\ring{6|ar}`.")


def user_prompt(lessons_text: str, count: int) -> str:
    return (USER.format(lessons_text=lessons_text, count=count)
            + _draw_reminder(lessons_text))
