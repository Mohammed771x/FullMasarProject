# ==================================================
# 💲 core/tex_blocks.py — كتلُ «$…$» بين صالحةٍ ومشوّهة
# ==================================================
# 🔴 **ما رآه المالك (2026-09-10):** «شوف الأسطر السبعة حق اللاتكس، ضبطها كلها».
#
# ⚖️ المسحُ وجد **١٧٨ كتلة** لا سبعاً، وهي **صنفان لا صنف**:
#
#   ✅ **١٠٠ صالحة** — أكثرُها ترميزُ عناصرَ في الكيمياء:
#      «$^4_2He$» · «$[Ar]4S^{2}3d^{10}4P^{5}$» · «$F^{9}$».
#      هذه **محتوىً حقيقيّ**: يُنزع الدولار ويُسلَّم للرسّام.
#
#   ❌ **٧٨ مشوّهة** — بقايا استخراجٍ ضوئيّ فقدت معناها:
#      «$\dot{\omega} = \frac{\dot{\rho}}{r_{\underline{\omega}}}$» —
#      رموزٌ يونانية حلّت محلّ «ش» و«ف» و«نق» العربية، فلا هي معادلةٌ
#      ولا هي كلام. وأشدُّها صفحاتُ التكامل في كتاب المنطق: مصفوفاتٌ
#      كاملةٌ من الحشو.
#
# 🔴🔴 **ولماذا الحذف لا الإصلاح؟** لأن إصلاحها يعني **تأليفَ معادلاتٍ
#      لم يكتبها الكتاب** — واختراعُ فيزياءَ لطالبٍ في امتحانٍ أسوأ من
#      فراغٍ. والحذفُ يترك النصَّ العربيَّ حوله سليماً، وهو الذي يشرح.
#
# ⚖️ **والمعيار يستهدف الشوائب لا غيابَ الأرقام.** أوّلُ قاعدةٍ كتبتُها
#    («تبقى إن حملت رقماً») حذفت **«$Na^{+}$» و«$Cl^{-}$»** — أيوناتٌ
#    صحيحةٌ بلا رقمٍ ولا عربية. فصار الحدّ:
#      يُحذف ما فيه بيئةُ LaTeX (مصفوفة)، أو **حرفان يونانيّان فأكثر
#      بلا عربية** — واليونانيّ هنا بديلٌ ضوئيٌّ عن «س» و«ص» و«ف».
#    وما عداه يبقى: الأيونُ والصيغةُ والعددُ والكسرُ الصحيح.

import re

__all__ = ["strip_broken_tex", "strip_broken_runs"]

_SPAN = re.compile(r"\$([^$]{1,600})\$")
_ARABIC = re.compile(r"[\u0621-\u064a]")
_DIGIT = re.compile(r"[0-9٠-٩]")
# مصفوفةٌ أو بيئةٌ كاملة ⇒ حشوٌ يقيناً، مهما حملت من أرقام.
_ENV = re.compile(r"\\begin\{|matrix|\\end\{")
# ⚠️ **يونانيٌّ بالشكلين**: الحرفُ نفسُه «ω» أو أمرُه «\omega». فالمسحُ
#    قد يسبق الحارسَ أو يليه، ولا يجوز أن يتعلّق الحكمُ بترتيبهما —
#    وقعت فعلاً: نظّفتُ قبل الحارس فلم أجد يونانياً واحداً.
_GREEK = re.compile(
    r"[\u0370-\u03ff]|\\(?:omega|rho|mu|nu|tau|xi|zeta|varphi|phi|chi|psi"
    r"|eta|kappa|epsilon|sigma|lambda|theta|alpha|beta|gamma|delta)\b")
_LATIN = re.compile(r"[A-Za-z]")


def _readable(inner: str) -> bool:
    from .latex_guard import clean
    if _ENV.search(inner):
        return False
    plain = clean(inner)
    if len(_GREEK.findall(plain)) >= 2 and not _ARABIC.search(plain):
        return False
    return bool(_ARABIC.search(plain) or _DIGIT.search(plain)
                or _LATIN.search(plain))


# 🔴 **وبعضُ الحشو فقد دولارَه أصلاً.** خمسةُ أسطرٍ في الفيزياء والمنطق
#    تحمل «\frac{ω^{μ}}{ω^{ρ}}» بلا «$» يحدّه — إمّا لأن الاستخراج أسقط
#    أحد الطرفين أو لأن الكتلة تداخلت. فيلزم مسحٌ ثانٍ **بالمقياس نفسه**:
#    سلسلةٌ من الترميز والرموز، حرفان يونانيّان فأكثر، ولا حرفَ عربياً.
#
# ⚖️ وشرطُ «لا عربية» هو ما يحمي الاقتصاد: «\frac{Δ ك}{Δ س}» فيها Δ
#    يونانية لكنها بجانب «ك» و«س» — فهي معادلةٌ حيّة لا حشو.
# ⚠️ **بلا فراغٍ داخل السلسلة**: أوّلُ صياغةٍ ابتلعت `\frac{1}{2}` سليمةً
#    لأنها جاورت الحشوَ في سلسلةٍ واحدة. فالفراغُ حدٌّ، وكلُّ قطعةٍ تُحاكَم
#    وحدها.
_RUN = re.compile(
    r"[\\{}^_()+\-=/×÷.,:;|~\[\]'A-Za-z0-9\u0370-\u03ff]{8,}")


def _noise_run(m: "re.Match") -> str:
    run = m.group(0)
    if "\\" not in run and "^" not in run and "_" not in run:
        return run                      # نصٌّ لاتينيٌّ عاديّ لا ترميز
    if _ARABIC.search(run):
        return run
    if _ENV.search(run) or len(_GREEK.findall(run)) >= 2:
        return " "
    return run


def strip_broken_runs(text: str) -> str:
    """يحذف الحشوَ الذي فقد حدَّي «$» — بالمقياس نفسِه."""
    if not text or not _GREEK.search(text):
        return text
    return re.sub(r"[ \t]{2,}", " ", _RUN.sub(_noise_run, text))


def strip_broken_tex(text: str) -> str:
    """يُبقي كتل «$…$» المقروءة بلا دولارها، ويحذف المشوّهة."""
    if not text:
        return text
    if "$" not in text:
        # ⚠️ لا دولارَ ⇒ ما زال المسحُ الثاني لازماً: الحشو الذي فقد
        #    حدَّيه هو بالضبط ما لا يراه `_SPAN`.
        return strip_broken_runs(text)

    # 🔴 **ورياضياتُ العرض `$$…$$`** (2026-09-12): النمطُ يلتقط الزوجَ
    #    الداخليّ فيبقى دولارٌ على كلِّ طرف — ورآها المالك في معادلة
    #    التخمّر اللبني في الأحياء. و«$$» و«$» سواءٌ عندنا: كلاهما حدُّ
    #    كتلة، فتُوحَّد قبل الفحص.
    text = text.replace("$$", "$")

    def _one(m: "re.Match") -> str:
        inner = m.group(1)
        return inner if _readable(inner) else ""

    return strip_broken_runs(re.sub(r"[ \t]{2,}", " ", _SPAN.sub(_one, text)))
