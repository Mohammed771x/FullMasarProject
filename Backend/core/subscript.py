# 🔴🔴 **ما رآه المالك (2026-09-17):** «خصوصاً فوق تباديل وتوافيق… ضبّطها
#      عشان يطلع الرسّام مضبوط». والمسحُ كشف أعمقَ ممّا ظنّ:
#
#      الأُسُّ له آليةٌ كاملة منذ 2026-09-09 (`core/powers.to_power` ⇐
#      `\sup{}`)، **ودليلُه المنخفض لا آليةَ له أصلاً.** فالكتاب يكتب
#      «م_ط» معاملَ التمدّد و«ق_ج» قوةَ الجاذبية و«ن_i» الحالةَ الابتدائية،
#      ويصل الطالبَ **شرطةً سفليةً عارية**: «م_ط = ٠٫٠٠٢».
#
#      📏 **القياس (2026-09-17):** ١٠٠١ دليلاً في قيم المنهج (٧٥٨ فيزياء ·
#         ٨٨ كيمياء · ٨١ منطق · ٥٥ رياضيات · ١٦ أحياء)، و**٣٩٠ موضعاً في
#         المخزون يراها الطالبُ خاماً اليوم** — أي في سطرٍ لا ترميزَ فيه
#         أصلاً فلا يبلغه رسّامُ الرياضيات ([kMathTokens] بوّابةُ السطر).
#
# ⭐ والعلاجُ نظيرُ الأُسّ حرفاً بحرف: `\sub{…}` يرسمه التطبيق `ScriptNode`
#    منخفضاً. وبه يدخل السطرُ بوّابةَ الرسّام، فيُرسم الدليلُ **ويُرسم معه
#    كلُّ ما في السطر** من كسورٍ وجذورٍ كان محجوباً بغياب الترميز.
#
# 🔒 **والنطاق نفسُه** (`ROOT_SUBJECTS`): في التاريخ «________» فراغُ ملءٍ،
#    وفي الإنجليزية «___ is used for» فراغُ سؤال — لا دليلَ فيهما.

import re

from .roots import ROOT_SUBJECTS                    # نفس نطاق الجذر… ناقصاً
from .formula import FORMULA_SUBJECTS

__all__ = ["to_sub", "SUB_SUBJECTS"]

# 🔴🔴 **والكيمياء مستثناةٌ من نطاق الجذر** — وهو الاستثناءُ الوحيد:
#    «C_nH_{2n+2}» صيغةٌ عامّةٌ للألكانات، دليلُها **دليلُ ذرّات** يرسمه
#    [core/formula.py] يونيكوداً («H₂O»)، لا دليلٌ رياضيّ. ولمّا شملتُها
#    خرجت «C\sub{nH}_{2n+2}» — **قطعت الصيغةَ نصفين** وتركت نصفَها خاماً.
#    كشفها `test_nuclide.test_no_latex_command_survives_in_chemistry`،
#    والمسحُ أكّد: **٣٨ موضعاً في الكيمياء كلُّها صيغٌ ممسوخة، ولا واحدَ
#    منها دليلٌ رياضيٌّ حقيقيّ** — ولا موضعَ كيميائيٌّ واحد كان يظهر خاماً
#    للطالب أصلاً، فالاستثناءُ ربحٌ خالص.
SUB_SUBJECTS = frozenset(ROOT_SUBJECTS) - frozenset(FORMULA_SUBJECTS)


def is_sub_subject(subject: str) -> bool:
    return (subject or "").strip() in SUB_SUBJECTS

_ARABIC = r"ء-ي"

# 🛡️ ما يرسمه التطبيق بنفسه لا يُمسّ — نظير `powers._SHIELD` تماماً:
#    داخل `\chem{CO_2}` و`\ring{}` و`\nuc{}` الشرطةُ **دليلُ ذرّاتٍ**
#    يرسمه الرسّامُ الكيميائي، ولو لُفّت بـ`\sub{}` لتلفت الصيغة.
_SHIELD = re.compile(r"\\(?:chem|ring|nuc)\{[^{}]*\}")

# 📖 القاعدةُ: محرفٌ يصحّ أن يُدَلَّ عليه — حرفٌ أو رقمٌ أو قوسٌ مغلق.
#    ⚠️ و**لا فراغ**: «كلمة _ كلمة» ليست دليلاً.
# 🔤 واليونانيةُ منها: «σ_S» و«σ_P» الانحرافان المعياريان في المنطق.
_GREEK = r"\u0370-\u03ff\u1f00-\u1fff"
_BASE = r"[" + _ARABIC + _GREEK + r"A-Za-z0-9٠-٩\)\]]"

# 🔴 **والقاعدةُ اللاتينية محرفٌ مفرد**: رموزُ الكتاب «R_H» و«T_1» و«n_i»
#    محرفٌ واحد. ولو قُبلت الكلمةُ لالتقط «snake_case_name» في مثال برمجةٍ
#    دليلاً — والفارقُ حرفٌ لاتينيٌّ يسبق القاعدة.
_NOT_WORD = r"(?<![A-Za-z][A-Za-z])(?<![A-Za-z]_)"

# 🔴 **الفراغُ المتكرّر ليس دليلاً**: «البيعة أول نواة لـ ________» تمرينُ
#    ملءٍ في التاريخ (١٦ موضعاً) و«___ is used» في الإنجليزية (٣).
#    فالشرطة **مفردةٌ** لا سلسلة — قبلها وبعدها.
#
# 🔗 **والدليلُ يتسلسل**: «م_فراغ_وسط» معاملُ انكسارٍ نسبيّ في الفيزياء
#    (٩ مواضع). ولمّا منعتُ «_» بعد الجسم خرجت «م_فراغ\sub{وسط}» —
#    نصفُها مرسومٌ ونصفُها خام، **وتتغيّر لو أُعيد التشغيل**. وهو ما
#    كشفه فحصُ الثبات عند التكرار قبل الكتابة.
_BRACED = re.compile(_NOT_WORD + r"(?<=" + _BASE + r")_(?!_)\{([^{}]{1,40})\}")

# 📐 دليلٌ عارٍ: «م_ط» · «ن_i» · «ق_٢» · «م_توض» (دليلٌ عربيٌّ مختصر).
#    ⚖️ **وحدُّ الطول أربعةُ محارف**: «م_توض» و«م_ضح» في الفيزياء دليلانِ
#       حقيقيّان، و**ما طال عن ذلك كلمةٌ** — ولو قُبلت الكلمةُ لابتلع
#       الدليلُ «snake_case» في أمثلة البرمجة ونصوصَ الحاسوب.
_BARE = re.compile(
    _NOT_WORD + r"(?<=" + _BASE + r")_(?!_)"
    r"([" + _ARABIC + _GREEK + r"A-Za-z0-9٠-٩]{1,4})"
    r"(?![" + _ARABIC + r"A-Za-z0-9٠-٩])")


def _wrap(body: str) -> str:
    body = body.strip()
    return "\\sub{%s}" % body if body else "_"


def _convert(chunk: str) -> str:
    chunk = _BRACED.sub(lambda m: _wrap(m.group(1)), chunk)
    chunk = _BARE.sub(lambda m: _wrap(m.group(1)), chunk)
    return chunk


def to_sub(text: str, subject: str = "") -> str:
    """يحوّل «م_ط» و«ن_{i}» إلى `\\sub{…}` — في المواد الرياضية وحدها.

    ⚠️ **تُنادى بعد `to_counting` و`to_nuclide`**: «^ن ل_ر» تباديلُ لا
       دليل، و«^235_92U» رمزُ نواةٍ وحدةً واحدة. ومَن سبقها إليهما
       أتلفهما — وهي العلّةُ نفسُها التي وثّقها [core/nuclide.py].
    """
    if not text or "_" not in text or not is_sub_subject(subject):
        return text

    out, last = [], 0
    for m in _SHIELD.finditer(text):          # 🛡️ الصيغُ الكيميائية تُعبَر
        out.append(_convert(text[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_convert(text[last:]))
    return "".join(out)
