# ══════════ أوامر تنسيقٍ بحتة: تُحذف ويبقى مضمونها ══════════
# ⚠️ `\left(` و`\right)` تحيطان بقوسٍ حقيقيّ — يُحذف الأمر ويبقى القوس.
FORMATTING = [
    r"\left", r"\right", r"\quad", r"\qquad", r"\,", r"\;", r"\!",
    r"\displaystyle", r"\textstyle", r"\limits", r"\nolimits",
]

# ══════════ أوامر بوسيطٍ واحد: يبقى الوسيط ══════════
# `\text{كلام}` ⇒ «كلام» · `\mathrm{د}` ⇒ «د».
# ⚖️ أوامرُ تغليفٍ: يُبقى ما بين قوسيها ويُحذف اسمُها.
#    و`dot`/`tilde`/`underline`/`bar` زخارفُ تشكيلٍ فوق الرمز، ومحتواها
#    هو المقدار — حذفُ الاسم وحده يُبقي المعنى.
_ARG_CMDS = ("text", "mathrm", "mathbf", "mathit", "textbf", "textit",
             "operatorname", "mbox", "hbox", "boxed",
             "dot", "ddot", "tilde", "underline", "overline", "bar",
             "hat", "vec")

# 🛡️ ما **لا** يُمسّ: الرسّام في التطبيق يفهمها.
KEPT = {r"\frac", r"\sqrt", r"\chem", r"\ring", r"\fact",
        r"\perm", r"\comb", r"\sup", r"\sub", r"\ovl", r"\nuc"}

_ARG_RE = re.compile(r"\\(" + "|".join(_ARG_CMDS) + r")\s*\{([^{}]*)\}")
_LEFTOVER_RE = re.compile(r"\\([a-zA-Z]+)")

# ══════════ رمزٌ رياضيّ يكتبه الموديل حرفاً لاتينياً ══════════
# 🔴 **علّة كشفها المسح:** «التركيب (ق o د)» — حرف `o` مكانَ رمز التركيب `∘`.
#    ظهر ٩ مرات في درس «قاعدة التسلسل» وحده. وهو ليس مصطلحاً من الكتاب بل
#    **رمزٌ خاطئ**: الطالب يرى حرفاً إنجليزياً حيث يجب أن يرى رمزاً رياضياً.
#
# ⚠️ والنمط ضيّقٌ عمداً — بين حرفين عربيين بمسافتين — كي لا يمسّ «o» في
#    كلمةٍ إنجليزية مشروعة مثل «Hyperbola».
_COMPOSE_RE = re.compile(r"(?<=[\u0600-\u06FF])\s+o\s+(?=[\u0600-\u06FF])")

# 🔴 **وعلّةٌ أختها كشفها مسحُ نصّ الكتاب نفسه:** «اتحاد الفترات» مكتوبٌ
#    بحرف `U` اللاتيني مكانَ رمز الاتحاد `∪` — «]-∞، ٢[ U ]٢، ∞[».
#    ظهر في ٥ مواضع من دروس التفاضل.
#
# ⚠️ والنمط محصورٌ بين قوسَي فترة عمداً: `U` حرفٌ شائع في الإنجليزية،
#    وهذه الدالة تمرّ على أجوبة **مادة الإنجليزي** أيضاً. و«] U [» لا
#    تقع في نثرٍ إنجليزيّ، بينما «A U B» تبقى كما هي — وهي خارج نطاقنا.
_UNION_RE = re.compile(r"(?<=[\]\[])\s*U\s*(?=[\]\[])")


# ⚗️ **سهمٌ بشرطٍ فوقه**: `\xrightarrow{حرارة شديدة}` — يصير الصيغةَ التي
#    يرسمها التطبيق شرطاً **فوق** السهم: `--[حرارة شديدة]-->`.
#
# ⚠️ **بعد فكّ `\text{}` لا قبله**: الشرطُ يأتي غالباً `\xrightarrow{\text{…}}`،
#    فلو عولج أولاً لبقي اسمُ الأمر داخل الشرط.
_XARROW = re.compile(r"\\xrightarrow\s*\{([^{}]*)\}")
_XARROW_BARE = re.compile(r"\\xrightarrow(?![A-Za-z])")
_XLEFT = re.compile(r"\\xleftarrow\s*\{([^{}]*)\}")


def clean(text: str) -> str:
    """يحوّل كل LaTeX لا يفهمه التطبيق إلى رمزٍ عربيّ أو يونيكود.

    ⚠️ **يُنادى بعد التوليد وقبل التسليم** — وعلى النصّ الكامل لا على أجزاء
       البثّ: أمرٌ مقطوعٌ بين جزأين (`\\in` ثم `t`) كان سيُحوَّل خطأً إلى «∈».
    """
    if not text:
        return text

    # 0️⃣ رمز التركيب: «ق o د» ⇒ «ق ∘ د».
    #
    # ⚠️ **قبل الخروج المبكر لا بعده**: هذا العطل يقع في نصٍّ **بلا أي
    #    backslash** («التركيب (ق o د)»)، فوضعُه بعد فحص `"\\" in text`
    #    كان يجعله لا يعمل أبداً — وهي علّةٌ وقعت فعلاً في أول تنفيذ.
    text = _COMPOSE_RE.sub(" ∘ ", text)
    text = _UNION_RE.sub(" ∪ ", text)

    if "\\" not in text:
        return text                     # 🚀 الغالبية العظمى تخرج من هنا

    # 1️⃣ أوامر الوسيط الواحد — تُفكّ أولاً كي لا يُحذف اسمها ويبقى وسيطها.
    #    وتُكرَّر للتعشيش: `\text{\mathrm{د}}`.
    for _ in range(3):
        text, n = _ARG_RE.subn(r"\2", text)
        if not n:
            break

    # 1️⃣.٥ سهمُ التفاعل بشرطه — بعد فكّ `\text{}` مباشرةً.
    text = _XARROW.sub(lambda m: "--[%s]-->" % m.group(1).strip()
                       if m.group(1).strip() else "-->", text)
    text = _XLEFT.sub(lambda m: "<--%s--" % m.group(1).strip()
                      if m.group(1).strip() else "<--", text)
    text = _XARROW_BARE.sub("-->", text)

    # 2️⃣ الرموز — الأطول أولاً كي لا تلتهم `\in` بدايةَ `\infty`.
    for cmd in sorted(SYMBOLS, key=len, reverse=True):
        if cmd in text:
            text = re.sub(re.escape(cmd) + r"(?![a-zA-Z])", SYMBOLS[cmd], text)

    # 3️⃣ أوامر التنسيق — تُحذف ويبقى ما حولها.
    for cmd in sorted(FORMATTING, key=len, reverse=True):
        if cmd in text:
            text = re.sub(re.escape(cmd) + r"(?![a-zA-Z])", "", text)

    # 4️⃣ أي أمرٍ باقٍ لم نعرفه — يُحذف اسمه ولا يُترك إنجليزياً.
    #
    # ⚠️ **هذه الخطوة هي الضمانة**: القوائم أعلاه لا تحيط بكل LaTeX، وموديلٌ
    #    قد يخترع أمراً لم نره. وترْكُ اسمٍ إنجليزيّ في شرحٍ عربيّ أسوأ من
    #    حذفه — والحذفُ يُبقي المعنى لأن الأمر تنسيقٌ في الغالب.
    def _drop(m):
        return m.group(0) if "\\" + m.group(1) in KEPT else ""

    text = _LEFTOVER_RE.sub(_drop, text)

    # 5️⃣ فراغُ LaTeX غير القابل للكسر «~» — يظهر محرفاً غريباً في العربية.
    text = text.replace("~", " ")

    # 6️⃣ شرطةٌ مائلة يتيمة — ما بعدها ليس أمراً أصلاً.
    #
    # 🔴 مصدرُها بياناتٌ استُخرجت من الكتاب فيها كتلُ LaTeX مشوّهة
    #    («$\frac{\dot{\rho}}{r_{\underline{\omega}}}$»): يُترجَم
    #    `\mu` إلى «μ» فتبقى الشرطةُ الثانية قبله فيرى الطالب «\μ».
    #    ولا تمسّ الأوامرَ المُبقاة لأنها متبوعةٌ بحرفٍ لاتيني.
    text = re.sub(r"\\(?![A-Za-z{])", "", text)

    # 7️⃣ فراغاتٌ مضاعفة خلّفها الحذف.
    text = re.sub(r"[ \t]{2,}", " ", text)
    return text


def audit(text: str) -> list[str]:
    """أوامر LaTeX الباقية بعد التنظيف — للاختبارات والتشخيص."""
    return [c for c in _LEFTOVER_RE.findall(text or "")
            if "\\" + c not in KEPT]
