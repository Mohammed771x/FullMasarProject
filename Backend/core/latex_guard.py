# 🔴 **ما رآه المالك:** شرحُ درسٍ في التكامل يظهر فيه «int» و«quad» و«left»
#    ككلماتٍ إنجليزية وسط النصّ العربي. والسبب أن الموديل يكتب `\int` و
#    `\quad` — والتطبيق لا يعرف إلا `\frac` و`\sqrt`، فيسقط الأمر ويبقى
#    اسمه نصّاً عارياً.
#
# 📊 **ومسحٌ لكل دروس الرياضيات (٦٤ شرحاً حقيقياً · 2026-09-09) أثبت أنه
#    ليس نادراً:** `\int` وحدها ٢٣ مرة، ومعها `\implies` · `\propto` ·
#    `\left` · `\right` · `\quad`.
#
# ⚖️ **ولماذا فلترٌ لا برومبت؟** البرومبت يمنع LaTeX منذ البداية — والموديل
#    يخالفه في ٣ من ٦٤. وامتثالُ الموديل احتماليّ بطبعه، فلا يبلغ ١٠٠٪ مهما
#    شُدِّد. والمطلوب هنا **يقين** لا احتمال ([قرار المالك]): «ما أبغى ولا
#    واحد بالمية». فالبرومبت يُقلّل، والفلتر يضمن.
#
# 🎯 والتحويل **إلى رمزٍ يفهمه الطالب** لا حذفٌ أعمى: `\int` تصير «∫»
#    (يونيكود يرسمه الخط)، و`\times` تصير «×». والحذفُ وحده كان سيُخرج
#    معادلةً ناقصة — وهي أسوأ من كلمةٍ إنجليزية لأنها **تبدو صحيحة**.

