# ==================================================
# ‾ core/overline.py — المرافق والمتمّمة والمشتقة
# ==================================================
# 🔴 **ما رآه المالك (2026-09-11):** «عين في عين شرطة… الترافق فيه مشكلة»
#    و«لما تكون الشرطة على القوس كامل، الشرطة تدخل مع القوس فما تطلع».
#
# ⭐ العلّة **محرفٌ مركّب**: الكتاب يكتب المرافقَ «ع̅» (ع + U+0305) والمتمّمة
#    «أَ» (أ + فتحة). والمحرفُ المركّب يعلو **حرفاً واحداً**؛ فإذا وقع بعد
#    قوسٍ مغلق — «(أ ∪ ب)َ» — التصق بالقوس فلم يظهر منه شيء.
#    فيُستبدل بترميز `\ovl{…}` يرسمه التطبيق حدّاً علوياً يطول بطول ما تحته.
#
# 🔴🔴 **وأخطرُ ما هنا: الفتحةُ نفسُها ثلاثةُ معانٍ في كتاب الرياضيات.**
#      مسحُ الوحدات (2026-09-11):
#        • **احتمالات** — «أَ» و«بَ»: **متمّمة الحادثة** ⇐ شرطة علوية (٤٥)
#        • **تفاضل وتكامل** — «صَ» و«ل َ(س)» و«دَ»: **المشتقة** ⇐ «′» (١٧)
#        • **هندسة** — «نَ»: **صورة النقطة** ⇐ «′» (٣)
#        • والتنوين «صً»: **المشتقة الثانية** ⇐ «″»
#      فلو رسمتُ كلَّ فتحةٍ شرطةً لصارت مشتقةُ الدالة «متمّمتَها».
#      والفارقُ **السياق**: «حـا(» أو «حادثة» أو «متمّمة» في السطر.
#
# ⚠️ والفتحة حركةٌ عربية عادية في كل نصّ — فالحدّان: **المادة رياضيات**،
#    و**حرفٌ مفردٌ** لا داخلَ كلمة («الَّذِي» فيها فتحاتٌ لا تُمسّ).

import re

__all__ = ["to_overline"]

_AR = "ء-ي"
_OVERLINE = "̅"          # المحرف المركّب: شرطة علوية
_FATHA = "َ"
_TANWEEN = "ً"

# سياقُ الاحتمالات — وحدَه يجعل الفتحةَ متمّمةً.
_PROB = re.compile(r"حـ?ا\s*\(|حادث|متمم|احتمال|عدم وقوع")

# «(…)̅» أو «(…)َ» — العلامة بعد قوسٍ مغلق ⇒ تعمّ القوسَ كلَّه.
_GROUP = re.compile(r"\(([^()]{1,60})\)\s*[" + _OVERLINE + _FATHA + r"]")
# «ع̅» — المحرف المركّب لا يكون إلا مرافقاً.
# ⚖️ و«ع̅1» مرافقُ «ع١» لا مرافقُ «ع» يتلوه واحد، فالدليلُ يدخل تحت الشرطة.
_LETTER_OVL = re.compile(
    r"([" + _AR + r"])" + _OVERLINE + r"([0-9٠-٩]?)")
# «أَ» — حرفٌ مفردٌ وفتحة.
# `\ovl{(\ovl{س})}` ⇒ `\ovl{\ovl{س}}`
_NESTED = re.compile(r"\\ovl\{\(\\ovl\{([^{}]{1,20})\}\)\}")

_LETTER_MARK = re.compile(
    r"(?<![" + _AR + r"])([" + _AR + r"])\s*([" + _FATHA + _TANWEEN + r"])"
    r"(?![" + _AR + r"])")


def to_overline(text: str, subject: str = "") -> str:
    """يحوّل المرافقَ والمتمّمة إلى `\\ovl{…}`، والمشتقةَ إلى «′»."""
    if (subject or "").strip() != "رياضيات":
        return text
    if not any(c in text for c in (_OVERLINE, _FATHA, _TANWEEN)):
        return text

    probability = bool(_PROB.search(text))

    # ١) القوسُ كاملاً — وهو الذي لا يظهر أصلاً في الكتاب.
    text = _GROUP.sub(lambda m: "\\ovl{(%s)}" % m.group(1), text)

    # ٢) المحرف المركّب على حرف ⇒ مرافقٌ دائماً.
    text = _LETTER_OVL.sub(
        lambda m: "\\ovl{%s%s}" % (m.group(1), m.group(2)), text)

    # ٣) الفتحة/التنوين على حرفٍ مفرد — بحسب السياق.
    def _mark(m: "re.Match") -> str:
        letter, mark = m.group(1), m.group(2)
        if probability:
            return "\\ovl{%s}" % letter
        return letter + ("″" if mark == _TANWEEN else "′")

    text = _LETTER_MARK.sub(_mark, text)

    # ⭐ «مرافق المرافق» شرطتان فوق **نفس المقدار** لا صندوقان متداخلان.
    #    «(ع̅)̅» تنتج `\ovl{(\ovl{ع})}` — والقوسان زينةٌ هنا، وإبقاؤهما
    #    يجعل الشرطة العليا أعرضَ من السفلى: «واحدة صغيرة واللي فوقها
    #    كبير» بنصّ المالك. فتُطوى.
    for _ in range(3):
        new = _NESTED.sub(r"\\ovl{\\ovl{\1}}", text)
        if new == text:
            break
        text = new
    return text
