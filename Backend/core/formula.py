# ==================================================
# ⚗️ core/formula.py — دليلُ الصيغة الكيميائية ينخفض: H2SO4 ⇐ H₂SO₄
# ==================================================
# 🔴 **طلبُ المالك (2026-09-12):** «H2SO4 — الاثنان بعد الـH تكون صغيرة
#    وتحته بشوية، والأربعة كذلك. الآن H2O تُكتب H و2 وبجنبها O، لا،
#    المفروض H و2 صغير تحت الـH. ولا تخلط بينها والأرقام اللي قبل:
#    في 2H2O الأولى كبيرة والثانية تحت».
#
# ⚖️ **ولماذا يونيكود لا ترميزٌ للرسّام؟** الصيغةُ تقع في **النثر** كما
#    تقع في المعادلة: «مثل الألدهيد الأروماتي (C6H5-CHO)» جملةٌ عربية
#    يرسمها الماركداون لا الرسّام. ومحرفُ `₂` حرفٌ حقيقيّ يظهر في كل
#    مسار — نثراً وجدولاً ومعادلةً — ويبقى صحيحاً عند النسخ والبحث.
#    وهو نظيرُ `_superscript` الذي يكتب «10²³» للمواد غير الرياضية.
#
# 📊 **وخطُّ التطبيق يرسمها**: Cairo فيه ₀-₉ و⁰-⁹ كاملةً (فُحص بـfontTools)،
#    فلا يقع الرقمُ في خطٍّ احتياطيّ مختلف الشكل.
#
# 📊 **ومسحُ المادّتين قبل الكتابة**: ٤٢٥٩ موضعاً فيه رمزٌ يليه رقم، منها
#    ٦١ ليست صيغةً كيميائية. وأخطرُها **التوزيع الإلكتروني** «ns2 np4»
#    و«dx2-y2»: رقمُها **مرفوعٌ** لا منخفض (عددُ الإلكترونات)، فاستُثنيت.

import re

# 🔒 الكيمياء والأحياء — نفسُ نطاق رسّام المعادلات (`REACTION_SUBJECTS`).
#    والفيزياءُ خارجَه: «m/s2» فيها وحدةٌ أُسُّها مرفوع لا دليلٌ منخفض.
FORMULA_SUBJECTS = frozenset({"كيمياء", "احياء"})

_DIGITS = str.maketrans("0123456789", "₀₁₂₃₄₅₆₇₈₉")

# ⚠️ ما بين قوسَي أمرٍ لا يُمسّ: `\nuc{235}{92}{U}` أرقامُها مرسومةٌ
#    طبقتين، و`\frac{1}{2}` بسطٌ ومقام.
_SHIELD = re.compile(r"\\[a-zA-Z]+(?:\{[^{}]*\})+")

# رمزٌ (أو قوسٌ مغلق) يليه رقمٌ **ملتصق**.
#    ⚠️ والذيلُ **استشرافٌ لا التهام**: لو ابتلع النمطُ الحرفَ
#       التالي لتخطّى دليلَ المقطع الذي يليه («Fe2O3» ⇒ «Fe₂O3»).
_TOKEN = re.compile(r"([A-Za-z]{1,6}|\))(\d+)(?=([+-]?)(.?))")

# ⚡ **شحنةٌ لا دليل**: «Zn2+» و«O2-» — الرقمُ عددُ الشحنات ويُكتب
#    **مرفوعاً** مع إشارته (Zn²⁺). ١٢٢ موضعاً في المادّتين.
#
# 🔴 **ولا تُحوَّل إلى يونيكود**: خطُّ التطبيق (Cairo) **لا يملك** «⁺» ولا
#    «⁻» (فُحص بـfontTools)، فتقع الإشارةُ في خطٍّ احتياطيّ مختلف الشكل
#    بجوار رقمٍ من خطّ التطبيق — أقبحُ من تركها كما هي.
#
# ⚖️ **والفارقُ عن رابطة السلسلة**: «CH3-CH2» شرطتُها يليها **حرف**،
#    وشحنةُ «Zn2+ +» يليها فراغٌ أو قوسٌ أو نهايةُ السطر.
_AFTER_SIGN_IS_BOND = re.compile(r"[A-Za-z]")

# 🔬 **مستوىً فرعيّ لا صيغة**: «ns2» · «np4» · «1s2» — الرقمُ عددُ
#    إلكترونات، يُكتب **مرفوعاً** في الكتاب. فلا يُنزَّل هنا ولا يُرفع:
#    تركُه كما هو أسلمُ من تخمينٍ يقلب معناه.
#    ومثلُها تسميةُ المدارات «dx2-y2» و«dz2»: الرقمُ أُسٌّ لا دليل.
_ORBITAL = re.compile(r"^[0-9n]?[spdf]$|^[dp]?[xyz]$")

# 🔤 **كلمةٌ إنجليزية لا رمز**: ثلاثةُ أحرفٍ صغيرة فأكثر («rapid2»).
#    والصيغُ رموزٌ كبيرةُ الأول («FADH2» · «CnH2»).
_WORD = re.compile(r"^[a-z]{3,}$")


# ══════════════════════════════════════════════════
# ⚡ الشحنةُ تُرفع: SO4-2 ⇐ SO₄²⁻
# ══════════════════════════════════════════════════
# 🔴 **سؤالُ المالك (2026-09-12):** «SO4 سالب 2 — إيش دخله؟ هل هو بق أو
#    من أصل المعادلة؟». **الجواب: من الكتاب** — أيونُ الكبريتات شحنتُه
#    ٢−، والكتابُ يكتبها «SO4-2» (١٠ مواضع).
#
# ⚖️ **لكن عرضَها مسطّحةً مشكلةٌ حقيقية**: «SO₄-2» تُقرأ **طرحاً** لا
#    شحنة. والكتابُ نفسُه يقول إن الصيغ مترادفة — نصُّه حرفياً:
#    «O2- = O-- = O-2 = O-II» — فتوحيدُها إلى الصورة القياسية **تصحيحُ
#    شكلٍ لا تغييرُ محتوى**: العددُ ثم الإشارةُ مرفوعين (O²⁻).
#
# 📊 **ومسحُ المادّتين**: «Na+» ٣٨٦ · «Cu2+» ١٢٤ · «SO4-2» ١٠.
#
# ⚠️ **و«He-4» نظيرٌ لا شحنة** (٨ مواضع: He-4 · H-2 · H-3): فالإشارةُ
#    السالبة المتبوعةُ برقمٍ لا تكون شحنةً إلا إذا سبقها **رقم**
#    («SO4-2»)؛ وإن سبقها حرفٌ فهو اسمُ نظير ويُترك.
_SUPS = str.maketrans("0123456789+-", "⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻")

# 1️⃣ «Cu2+» · «O2-» · «SO42-» — الرقمُ الأخير شحنةٌ وما قبله دليل.
#
# 🔴 **و«SO42-» كتابةٌ مضغوطة** يكتبها الكتاب في جدول الجهود: الكبريتات
#    دليلُها ٤ وشحنتُها ٢−. فيُقرأ **آخرُ رقمٍ** شحنةً والباقي دليلاً —
#    وهو القراءةُ القياسية لهذه الصورة (PO₄³⁻ · CO₃²⁻).
_CHARGE_NUM_SIGN = re.compile(
    r"(?<=[A-Za-z)])(\d*)(\d)([+-])(?![A-Za-z0-9])")

# 2️⃣ «SO4-2» — الإشارةُ قبل العدد، والعددُ الذي **قبلها** دليلٌ لا شحنة.
#    ⚠️ ويُشترط حرفٌ قبل ذلك الدليل كي لا يُلتقط مدىً («10-2 سم»).
_CHARGE_SIGN_NUM = re.compile(r"(?<=[A-Za-z]\d)([+-])(\d)(?![0-9A-Za-z])")

# 2️⃣.٥ «SO4 2-» — بفراغٍ بينهما، كما في جدول أسماء الأيونات (٣٣ موضعاً).
#    والفراغُ يسقط: «SO₄²⁻» صيغةٌ واحدة لا اثنتان.
_CHARGE_SPACED = re.compile(r"(?<=[A-Za-z])(\d+)\s(\d)([+-])(?![A-Za-z0-9])")

# 3️⃣ «Zn+2» — موجبٌ قبل العدد.
#
# 🔴 **ويُشترط رمزُ عنصرٍ كاملاً قبله** (حرفٌ أو حرفان لا يسبقهما حرفٌ ولا
#    رقم): وبغيره التُقطت «CnH2n+2» — الصيغةُ العامة للألكانات — فخرجت
#    «CnH₂n²⁺»، و«2l+1» في أعداد الكمّ صارت «2l¹⁺». كشفهما المسحُ.
_CHARGE_PLUS_NUM = re.compile(
    r"(?<![A-Za-z0-9])([A-Z][a-z]?)\+(\d)(?![0-9A-Za-z])")

# 4️⃣ «Na+» · «Cl-» · «2e-» — إشارةٌ مجرّدة.
#    ⚠️ ولا تُمسّ «O--»: إشارتان متتاليتان صورةٌ أخرى في جدول المترادفات.
_CHARGE_BARE = re.compile(r"(?<=[A-Za-z)])([+-])(?![A-Za-z0-9+-])")


# 📖 **جدولُ مترادفات الترميز** — سطرٌ يعلّم أن الصيغ سواء:
#    «Mg2+ = Mg++ = Mg+2 = MgII» و«O2- = O-- = O-2 = O-II» (سطران).
#
# ⚠️ **ولا تُرفع شحنتُه**: توحيدُ صورتين منه إلى واحدة يُلغي الدرسَ
#    نفسَه — يقرأ الطالبُ «Mg²⁺ = Mg++ = Mg²⁺». فالسطرُ يُترك كما كتبه
#    الكتاب، وهو شرطُ المالك: «لا تعدل أي محتوى».
_NOTATION_TABLE = re.compile(
    r"[A-Z][a-z]?\d?[+-]{1,2}\s*=\s*[A-Z][a-z]?\d?[+-]{1,2}")


def _raise_charges(text: str) -> str:
    """يرفع الشحنة إلى الصورة القياسية: العددُ ثم الإشارة (O²⁻).

    ⚠️ **قبل إنزال الدليل**: «SO4-2» رقمُها الأول دليلٌ والثاني شحنة،
       فلو نزّلنا أولاً لالتبس الاثنان.
    """
    if _NOTATION_TABLE.search(text):
        return text
    out = _CHARGE_NUM_SIGN.sub(
        lambda m: m.group(1).translate(_DIGITS)
        + (m.group(2) + m.group(3)).translate(_SUPS), text)
    # ⭐ ويُقلب الترتيبُ إلى القياسيّ: «-2» ⇐ «²⁻». والكتابُ نفسُه يقول
    #    إنها مترادفة — نصُّه: «O2- = O-- = O-2 = O-II».
    out = _CHARGE_SPACED.sub(
        lambda m: m.group(1).translate(_DIGITS)
        + (m.group(2) + m.group(3)).translate(_SUPS), out)
    out = _CHARGE_SIGN_NUM.sub(
        lambda m: (m.group(2) + m.group(1)).translate(_SUPS), out)
    out = _CHARGE_PLUS_NUM.sub(
        lambda m: m.group(1) + (m.group(2) + "+").translate(_SUPS), out)
    return _CHARGE_BARE.sub(lambda m: m.group(1).translate(_SUPS), out)


def to_subscript(text: str, subject=None) -> str:
    """ينزّل دليلَ الصيغة في الكيمياء والأحياء وحدهما.

    ⚠️ **ولا يمسّ المعامل**: «2H2O» أولُها معاملٌ لأنه لا يسبقه رمز،
       وثانيها دليلٌ لأنه يلي «H». وهو نصُّ طلب المالك حرفياً.
    """
    if not text or (subject or "").strip() not in FORMULA_SUBJECTS:
        return text
    # ⚠️ والحرسُ يقبل الشحنةَ أيضاً: «Na+ + Cl-» بلا رقمٍ بعد حرف.
    if not re.search(r"[A-Za-z)][\d+-]", text):
        return text

    shield: list[str] = []

    def _stash(m):
        shield.append(m.group(0))
        return "\x00%d\x00" % (len(shield) - 1)

    masked = _SHIELD.sub(_stash, text)

    def _one(m):
        head, digits, sign, after = m.groups()
        if _ORBITAL.match(head) or _WORD.match(head):
            return m.group(0)
        # ⚡ شحنةٌ: رقمٌ ثم إشارةٌ لا يليها حرف ⇒ تُترك كما كتبها الكتاب.
        if sign and not _AFTER_SIGN_IS_BOND.match(after or " "):
            return m.group(0)
        return head + digits.translate(_DIGITS)

    out = _raise_charges(masked)
    out = _TOKEN.sub(_one, out)
    for i, raw in enumerate(shield):
        out = out.replace("\x00%d\x00" % i, raw)
    return out
