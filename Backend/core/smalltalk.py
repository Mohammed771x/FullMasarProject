# 🔴 **الترقيمُ العربيّ داخل نطاق الحروف** — نفسُ العلّة التي كلّفت نصفَ
#    المطابقة اللفظية ([common._TERM_TRIM]): «؟» و«،» و«؛» تقع داخل
#    `؀-ۿ`، فـ«من أنت؟» لا تطابق «من انت» ما لم تُنزع صراحةً.
_ARABIC_PUNCT = "؟،؛٪٫٬…ـ"
_PUNCT = re.compile("[^\\w؀-ۿ\\s]+|[" + _ARABIC_PUNCT + "]+")


def _clean(text: str) -> str:
    """النصُّ موحَّداً بلا ترقيمٍ ولا رموزٍ تعبيرية ولا كلماتِ نداء."""
    norm = _normalize_for_search(text or "")
    norm = _PUNCT.sub(" ", norm)
    words = [w for w in norm.split() if w and w not in _FILLERS]
    return " ".join(words)


def intent_of(text: str):
    """نيّةُ الرسالة إن كانت اجتماعيةً **بكاملها**، وإلا `None`."""
    cleaned = _clean(text)
    if not cleaned or len(cleaned) > 60:
        return None
    for name, phrases in _INTENTS:
        if cleaned in phrases:
            return name
    return None


def _where(subject: str, unit: str = "") -> str:
    unit = (unit or "").strip()
    if unit and unit != "الكل":
        return f"حصة {subject} — وحدة «{unit}»"
    return f"حصة {subject}"


def _has_content(req) -> bool:
    """هل لهذه المادة محتوًى على هذا الصف أصلاً؟

    ⚖️ **ولا نرحّب بطالبٍ في حصةٍ فارغة**: مادةٌ محتواها قيد الإضافة يجب
       أن تقول ذلك ولو كانت الرسالةُ تحية — وإلا رحّبنا به في «حصة
       رياضيات» ثم صدمناه بـ«قيد الإضافة» في أول سؤال.
    """
    try:
        from .capabilities import describe
        info = describe(getattr(req, "grade", 0), getattr(req, "track", ""),
                        (getattr(req, "subject", "") or "").strip())
    except Exception:
        return True                     # تعذّر الفحص ⇒ لا نمنع التحية
    return bool(info.get("lessons", {}).get("available")
                or info.get("pages", {}).get("available"))


