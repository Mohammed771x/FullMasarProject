_RUN = re.compile(r"\d[\d,]*")
_PERCENT = re.compile(r"(\d[\d,]*)\s*%")

# أقل طول يُعدّ «ادعاءَ رقم»: ما دونه ترقيمُ قوائم وأعمارٌ مذكورة أصلاً.
_MIN_DIGITS = 3


def _numbers_in(text: str) -> set:
    """أرقام النصّ موحَّدةً: عربية → لاتينية، بلا فواصل آلاف.

    نُبقي: ما طوله ≥ 3 خانات (المبالغ والسنوات) **وكل نسبة مئوية** مهما قصرت
    («70%» ادعاءٌ يستحق التحقق، بينما «2)» في قائمة لا يستحق).
    """
    if not text:
        return set()
    plain = text.translate(_DIGITS)
    out = set()
    for raw in _PERCENT.findall(plain):
        out.add(raw.replace(",", ""))
    for raw in _RUN.findall(plain):
        clean = raw.replace(",", "")
        if len(clean) >= _MIN_DIGITS:
            out.add(clean)
    return out


def unverified_numbers(answer: str, sources) -> list:
    """أرقام الرد التي لا أصل لها في أيٍّ من [sources]. مرتّبة ثابتاً للاختبار."""
    allowed = set()
    for src in sources:
        allowed |= _numbers_in(src or "")
    return sorted(_numbers_in(answer) - allowed)


NUMBER_WARNING = (
    "\n\n⚠️ **تنبيه:** الأرقام التالية غير مذكورة في بيانات هذه المنحة لدينا "
    "({numbers}) — تحقّق منها في الموقع الرسمي قبل الاعتماد عليها."
)

