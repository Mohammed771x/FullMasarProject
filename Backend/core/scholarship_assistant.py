def build_history(chat_history) -> list:
    """آخر HISTORY_LAST_N رسالة مقصوصة — مصدر الرقم واحد ([27§6])."""
    if not chat_history:
        return []
    out = []
    for message in list(chat_history)[-HISTORY_LAST_N:]:
        if isinstance(message, dict):
            role = str(message.get("role", "user"))
            text = str(message.get("content", message.get("text", "")))
        else:
            role = str(getattr(message, "role", "user"))
            text = str(getattr(message, "text", ""))
        text = text.strip()[:HISTORY_MAX_CHARS]
        if not text:
            continue
        out.append({"role": "assistant" if role in ("assistant", "ai") else "user",
                    "content": text})
    return out


