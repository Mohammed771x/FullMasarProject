def _bullets(title: str, items) -> str:
    if not items:
        return ""
    lines = "\n".join(f"- {i}" for i in items)
    return f"\n\n{title}:\n{lines}"


def scholarship_card(sch: dict) -> str:
    """كل ما يعرفه المساعد عن هذه المنحة — لا أكثر ولا أقل."""
    funding = "ممولة بالكامل" if sch.get("funding_type") == "full" else "تمويل جزئي"
    parts = [
        f"الاسم: {sch.get('name', '')}",
        f"الدولة: {sch.get('country', '')}",
        f"نوع التمويل: {funding}",
    ]
    if sch.get("degree_levels"):
        parts.append("المراحل: " + "، ".join(sch["degree_levels"]))
    if sch.get("open_date"):
        parts.append(f"فتح التقديم: {sch['open_date']}")
    if sch.get("close_date"):
        parts.append(f"إغلاق التقديم: {sch['close_date']}")
    parts.append("الحالة الآن: " + store.STATUS_LABELS.get(sch.get("status", "open"), ""))

    days = sch.get("days_left")
    if isinstance(days, int) and 0 <= days < 9999 and sch.get("status") == "open":
        parts.append(f"المتبقي على الإغلاق: {days} يوماً")

    if sch.get("website"):
        parts.append(f"الموقع الرسمي: {sch['website']}")
    if sch.get("short_desc"):
        parts.append(f"نبذة سريعة: {sch['short_desc']}")

    body = "\n".join(parts)
    if sch.get("about"):
        body += f"\n\nعن المنحة:\n{sch['about']}"
    body += _bullets("المزايا", sch.get("benefits"))
    body += _bullets("الشروط والمتطلبات", sch.get("requirements"))
    body += _bullets("الوثائق المطلوبة", sch.get("documents"))
    body += _bullets("خطوات التقديم", sch.get("how_to_apply"))
    if sch.get("fields"):
        body += "\n\nالمجالات المتاحة: " + "، ".join(sch["fields"])
    return body


