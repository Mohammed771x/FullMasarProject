def turn_state(chat_history) -> str:
    """السطر الذي يجعل الموديل يعرف موقعه من المحادثة.

    ⚠️ **هذا أهم سطر في البرومبت كله.** بدونه يظن الموديل أن كل رسالة هي
    الأولى، فيرحّب ويعيد الديباجة في كل رد — وهو بالضبط ما اشتكى منه المالك.
    """
    turns = 0
    for message in (chat_history or []):
        role = message.get("role") if isinstance(message, dict) else getattr(message, "role", "")
        if role in ("user", "assistant", "ai"):
            turns += 1

    if turns == 0:
        return ("هذه **أول رسالة** في المحادثة: رحّب بسطر قصير واحد ثم ادخل "
                "في الإجابة مباشرةً.")

    exchanges = max(1, turns // 2)
    return (f"هذه **متابعة** لمحادثة جارية (سبقها نحو {exchanges} تبادلاً). "
            "لا تحية، ولا تعريف بنفسك، ولا إعادة لما قلته سابقاً — "
            "أجب مباشرةً كأنك تكمل الكلام.")


