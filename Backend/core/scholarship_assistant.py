async def ask(sch: dict, question: str, chat_history, clients: dict, sink=None) -> dict:
    """يجيب على سؤال الطالب. الفشل رسالةٌ ودّية لا انهيار."""
    text = (question or "").strip()[:MAX_QUESTION_CHARS]
    if not text:
        return {"answer": "اكتب سؤالك عن المنحة وسأجيبك 😊", "ok": False}

    client = clients.get("gemini")
    if client is None:
        return {"answer": "⚠️ مساعد المنح غير متاح حالياً. حاول بعد قليل.", "ok": False}

    messages = [{
        "role": "system",
        "content": build_system(sch, store.get_prompt(sch["id"]), chat_history),
    }]
    messages += build_history(chat_history)
    messages.append({"role": "user", "content": text})

    try:
        answer = (await streaming.complete(
            client, model=MODEL, messages=messages, sink=sink,
            timeout=_AI_TIMEOUT, max_tokens=_MAX_TOKENS, temperature=0.4) or "").strip()
    except asyncio.TimeoutError:
        return {"answer": "⏳ تأخّر الرد. أعد إرسال سؤالك من فضلك.", "ok": False}
    except Exception as e:
        print(f"⚠️ مساعد المنحة: {e}")
        return {"answer": "⚠️ تعذّر الوصول للمساعد الآن. حاول بعد قليل.", "ok": False}

    if not answer:
        return {"answer": "لم أفهم سؤالك جيداً — أعد صياغته من فضلك 🙏", "ok": False}

    # 🔢 شبكة الأمان: رقمٌ لا أصل له في مصادرنا يُنبَّه عليه صراحةً.
    sources = [scholarship_card(sch), text]
    sources += [m["content"] for m in build_history(chat_history)]
    stray = unverified_numbers(answer, sources)
    if stray:
        print(f"⚠️ أرقام بلا مصدر في رد المساعد ({sch['id']}): {stray}")
        answer += NUMBER_WARNING.format(numbers=" · ".join(stray))

    return {"answer": answer, "ok": True, "scholarship_id": sch["id"],
            "unverified_numbers": stray}
