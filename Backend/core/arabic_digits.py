# ==================================================
# 🔴 **ما رآه المالك:** شرحُ الرياضيات والمنطق يخرج بأرقامٍ لاتينية
#    (1, 2, 3) بينما الكتاب اليمني — والطالب — يقرأ ٠١٢٣.
#
# ⚖️ **ولماذا فلترٌ لا برومبت؟** لنفس سبب [core/latex_guard.py]: امتثال
#    الموديل احتماليّ، والمطلوب يقين. والبرومبت يبقى مفيداً (يجعل النصّ
#    متّسقاً من أوّله) لكنه لا يُغني عن الضمانة.
#
# ⚠️ **والنطاق مقصود**: الرياضيات والمنطق والفيزياء. تعميمُه على كل المواد
#    كان سيُخرج «H٢O» و«CO٢» في الكيمياء — أي يكسر رمزاً صحيحاً.
#
# 🔬 **والفيزياء أُضيفت بنصّ المالك (2026-09-12):** «حوّل الأرقام كلها
#    عربية، والسالب يكون من جهة يمين الرقم». والسالبُ يمينَ عددِه يقع
#    **وحده** حين يصير العددُ عربياً: الرقم العربي-الهندي صنفُه AN،
#    فتُحلّ الإشارةُ المجاورة له محايدةً فتأخذ اتجاهَ السطر (RTL) فتقع
#    يمينَه — فلا حاجة إلى `latinSign` في الفيزياء أصلاً.

import re

_WEST = "0123456789"
_EAST = "٠١٢٣٤٥٦٧٨٩"
_MAP = str.maketrans(_WEST, _EAST)

# 🛡️ ما لا يُمسّ إطلاقاً:
#    • `\chem{H2O}` و`\ring{...}` — الرسّام يقرأ رموزها لاتينيةً بالتعريف
#    • رقمٌ ملاصقٌ لحرفٍ لاتيني («H2O» · «CO2» · «x2») — رمزٌ لا عدد.
#      و**السلسلةُ كاملة** لا الرقمُ الملاصقُ وحده: «500mA» كان يخرج
#      «٥٠0mA» و«C141» يخرج «C1٤١» — تحويلٌ نصفيّ أقبحُ من لا تحويل.
#      (٩ رموزٍ من ٦٦ في كتاب الفيزياء — قِيست 2026-09-12.)
#    • اسمُ أمرٍ لاتيكيّ (`\times` · `\frac`) — حرفُه الأخير يلاصق رقمَ
#      **المعادلة** لا رقمَ رمزٍ: «\times10» عددُه عشرة، ولولا حجبُ
#      الاسم لظُنّ الـ«1» جزءاً من رمزٍ لاتيني فنجا وحدَه ⇒ «×1٠».
#      (٣ أسطر في كتاب الفيزياء — قِيست 2026-09-12.)
_PROTECTED = re.compile(r"\\(?:chem|ring)\{[^{}]*\}|\\[a-zA-Z]+")
_LATIN_BOUND = re.compile(r"(?<=[A-Za-z])\d+|\d+(?=[A-Za-z])")

# 🔒 المواد التي تخرج أرقامُها عربية — والباقي يمرّ نصُّه كما هو.
#
# 📊 **ومسحُ كتاب الفيزياء (٢٦٧٣٨ سطراً) قبل الإضافة:** ٣٩٧ موضعاً فيه
#    رقمٌ ملاصقٌ لحرفٍ لاتيني (T1 · T2 · W0 · f0 · 500mA) — كلُّها رموزٌ
#    لا أعداد، ويحجبها `_LATIN_BOUND` أعلاه. و٥٤١٥ موضعاً رقمُه ملاصقٌ
#    لحرفٍ **عربي** (ق1 · ح2 · ض1) — وهي دلائلُ متغيّراتٍ يكتبها الكتاب
#    نفسُه عربيةً في ٤٤ موضعاً («ل١» · «T٠» · «f٢») فتوحيدُها هو المطلوب.
ARABIC_DIGIT_SUBJECTS = frozenset({"رياضيات", "منطق", "فيزياء"})


def for_subject(text: str, subject=None) -> str:
    """الأرقام عربية في مواد `ARABIC_DIGIT_SUBJECTS` وحدها.

    ⚖️ **قائمةٌ بيضاء لا سوداء**: ما لم تُذكر المادة صراحةً يمرّ نصُّها
       حرفياً — نفس مبدأ [core/nuclide.py] و[core/formula.py].
    """
    if (subject or "").strip() not in ARABIC_DIGIT_SUBJECTS:
        return text
    return to_arabic(text)


def to_arabic(text: str) -> str:
    """يحوّل أرقام النصّ إلى الأرقام العربية (٠-٩) ويحمي الرموز اللاتينية."""
    if not text:
        return text
    if not any(c in _WEST for c in text):
        return text                      # 🚀 لا رقم لاتينياً أصلاً

    # ١) اعزل ما لا يُمسّ برموزٍ نائبة لا تظهر في نصٍّ عربي
    kept: list[str] = []

    def _stash(m):
        kept.append(m.group(0))
        return f"\x00{len(kept) - 1}\x00"

    text = _PROTECTED.sub(_stash, text)
    text = _LATIN_BOUND.sub(_stash, text)

    # ٢) حوّل الباقي
    text = text.translate(_MAP)

    # ٣) أعد ما عُزل — والفهرس صار عربياً بعد التحويل فنقبل الشكلين
    def _pop(m):
        idx = m.group(1).translate(str.maketrans(_EAST, _WEST))
        return kept[int(idx)]

    return re.sub(r"\x00(\d+|[٠-٩]+)\x00", _pop, text)
