MAX_ORDER = 9999


def _error(message: str):
    from .scholarships import ScholarshipError
    return ScholarshipError(message)


def min_gpa(value) -> int:
    """📊 **المعدّل المطلوب** — نسبةٌ مئويّة صحيحة، و`0` = «غير محدّد».

    🔴 **لماذا حقلٌ أصلاً؟** لم يكن في المنحة معدَّلٌ إطلاقاً، وكانت شاشةُ
       الطالب تستخرجه من نصّ الشروط بتعبيرٍ نمطيّ — يصيب غالباً ويُخطئ حين
       يذكر الشرطُ نسبةً أخرى (تمويلاً أو خصماً). فطلب المالك حقلاً صريحاً
       في اللوحة (2026-09-21). والاستخراجُ يبقى **احتياطاً** لمنحةٍ قديمةٍ
       لم يُملأ حقلُها بعد، فلا تفقد الشاشةُ ما كانت تعرضه.

    ⚖️ **رقمٌ لا نصّ:** نصٌّ حرٌّ يعني «85%» و«85 %» و«ممتاز» في ثلاث منحٍ،
       ولا يُقارَن ولا يُفرز. والنسبةُ المئويّة لغةُ الثانوية اليمنية،
       وصياغةُ العرض («٥٨٪+») تبقى قرارَ الواجهة لا المخزن.

    ⚠️ والفراغُ «غير محدّد» **لا صفراً**: منحةٌ بمعدّلِ صفرٍ لا معنى لها،
       وعرضُ «0%» على طالبٍ أسوأُ من السكوت.
    """
    text = str(value if value is not None else "").strip()
    if not text:
        return 0
    try:
        number = int(float(text))
    except (TypeError, ValueError):
        raise _error("❌ المعدّل المطلوب يجب أن يكون رقماً (نسبة مئوية) — مثل «70».")
    if number == 0:
        return 0
    if not 1 <= number <= 100:
        raise _error("❌ المعدّل المطلوب نسبةٌ مئويّة بين 1 و100 — أو اتركه فارغاً.")
    return number


def order(value) -> int:
    """🔢 ترتيبُ العرض — يُقصّ ولا يُرفض.

    ⚖️ **وهو عكسُ [min_gpa] عمداً**: ترتيبٌ غريبُ الصيغة يعني بطاقةً في
       غير موضعها، ومعدَّلٌ غريبُ الصيغة يعني **رقماً خاطئاً أمام طالب**.
       فالأول يُصحَّح بصمت والثاني يُوقِف الحفظ برسالة.
    """
    try:
        number = int(value or 0)
    except (TypeError, ValueError):
        number = 0
    return max(0, min(number, MAX_ORDER))
