# ==================================================
# ☢️ core/nuclide.py — رمزُ النواة: العدد الكتلي فوق الذرّي
# ==================================================
# 🔴 **ما رآه المالك على الشاشة (2026-09-12):** معادلاتُ الانشطار النووي
#    تخرج «Cl7₁³⁵» و«\sup{235}_92U» — أرقامٌ مبعثرة حول الرمز بلا ترتيب.
#
# ⚖️ **والسببُ أن `^` و`_` يُعالَجان كلٌّ على حدة**: الأُسُّ يصير `\sup{235}`
#    والدليلُ يبقى `_92` خاماً، ثم يرتّبهما الاتجاهُ الثنائي كما يشاء —
#    فيسبق الرمزُ عددَيه وينقلب ترتيبُهما.
#
# ⭐ **وهما في الكتاب وحدةٌ واحدة**: العدد الكتلي **فوق** الذرّي، وكلاهما
#    **قبل** الرمز — ²³⁵₉₂U. فتُقرأ الثلاثة معاً وتُرسل رمزاً واحداً
#    `\nuc{الكتلي}{الذرّي}{الرمز}` يرسمه التطبيق طبقتين.
#
# 📊 **ومسحُ المنهج:** ١٣٢ موضعاً في الكيمياء (وحدة «الطاقة والتفاعلات
#    النووية» وما حولها)، و**صفر** في بقية المواد — كتابُ الفيزياء يكتبها
#    أرقاماً مفرّقة بمسافات («226 88 Ra») فلا يبلغها هذا النمط أصلاً.

import re

# 🔒 الكيمياء وحدها — راجع المسح أعلاه. والقائمةُ بيضاء: ما لم تُذكر
#    المادة صراحةً يمرّ نصُّها كما هو.
NUCLIDE_SUBJECTS = frozenset({"كيمياء"})

# ☢️ `^235_92U` · `^1_0n` · `^4_2He` — وقد يأتي بلا رمزٍ بعده:
#    «^12_6» في جدولِ نظائر، فيُرسم العددان وحدهما.
#
# ⚠️ والرمزُ **لاتينيٌّ قصير** (`U` · `He` · `n`) أو عربيٌّ قصير — ولا
#    يمتدّ إلى الكلمة التي بعده: «^24_11Na يتحلل» رمزُها «Na» لا «Na يتحلل».
#
# ⚠️ والفراغُ **داخل** المجموعة الاختيارية: لولا ذلك لالتهمه النمطُ حين
#    لا رمزَ بعده فالتصقت الكلمةُ التالية بالرمز («^12_6 نظير»).
#
# 🔴 **والعدد الذرّي قد يحمل إشارة** (2026-09-12): جسيمُ بيتا الموجب
#    `^0_+1β` والسالب `^0_-1β` والإلكترون `^0_-1e` — ١٧ موضعاً كانت
#    تسقط من النمط كلَّها فتصل الطالبَ خاماً.
#
# ⚠️ والرمزُ قد يكون يونانياً: β · α · γ — وهي رموزُ الإشعاع نفسِها.
_NUC = re.compile(
    r"\^([+-]?\d{1,3})_([+-]?\d{1,3})"
    r"(?:\s*([A-Za-z]{1,2}(?![A-Za-z])|[ء-ي]{1,2}(?![ء-ي])|[αβγνe]))?"
)


def to_nuclide(text: str, subject=None) -> str:
    """يحوّل `^A_ZSym` إلى `\\nuc{A}{Z}{Sym}` في الكيمياء وحدها.

    ⚠️ **تُنادى قبل `to_power`**: وإلا ابتلع الأُسُّ العددَ الكتلي وحده
       (`\\sup{235}`) وترك الذرّيَّ دليلاً عارياً — وهو عين ما ظهر للطالب.
    """
    if not text or "^" not in text:
        return text
    if (subject or "").strip() not in NUCLIDE_SUBJECTS:
        return text

    def _sub(m):
        sym = m.group(3) or ""
        return "\\nuc{%s}{%s}{%s}" % (m.group(1), m.group(2), sym)

    return _NUC.sub(_sub, text)
