# 🔴 **ما طلبه المالك (2026-09-10):** «التباديل والتوافيق، الـل والقاف…
#    ويكون الـن فوق، والراء تحت».
#
# ⭐ فالرمز في الكتاب اليمني: حرفٌ في الوسط، **ن مرفوعةٌ عن يمينه**
#    و**ر منخفضةٌ عن يساره** — «ⁿل_ر» و«ⁿق_ر» — والتطبيق يرسمها من
#    `\perm{ن}{ر}` و`\comb{ن}{ر}`، نظير `\frac` و`\fact` تماماً.
#
# 🔴🔴 **وخطرُ هذا الملفّ أشدُّ من كل ما سبق: «ل» و«ق» حرفان عاديّان.**
#      مسحُ البيانات كشف أن التعميم كارثة:
#        • فيزياء «ق_ج» = قوة الجاذبية — **٨٥ موضعاً**
#        • فيزياء «ق س» و«ق ص» = مركّبتا القوة — **٤٨**
#        • رياضيات «س² **لو** س» — اللوغاريتم، و«قيمة **ل** إذا كان»
#        • رياضيات «|ن ق١| + |ن ق٢|» — بؤرتا القطع الناقص، لا توافيق
#        • فلسفة «القرن الـ**ق ٩**م»
#      ولذلك **حدّان**: المادة (رياضيات · منطق وحدهما — لا فيزياء)،
#      ثم **مقدارٌ حقيقيّ** على الجانبين: رقمٌ أو حرفٌ **مفردٌ** رمزيّ.
#      «إذا» ثلاثةُ أحرف فتُرفض، و«ن» حرفٌ واحد فتُقبل.

import re

__all__ = ["to_counting", "COUNTING_SUBJECTS"]

# ⚖️ العدّ درسٌ في الجبر والمنطق وحدهما. وإدخال الفيزياء يُتلف «ق_ج».
COUNTING_SUBJECTS = frozenset({"رياضيات", "منطق"})

_ARABIC = r"ء-ي"
# مقدارٌ مقبول: أرقام، أو حرفٌ عربيٌّ **مفرد** (ن · ر · م · س)، ويجوز أن
# يتبعه رقمٌ («ر1»). و«إذا» ثلاثةُ أحرف فتُرفض — وهذا ما يحمي «قيمة ل إذا».
_ATOM = r"(?:[0-9٠-٩]+|[" + _ARABIC + r"][0-9٠-٩]?)"

# 🔴 **الإشارة الملتصقة وحدها جزءٌ من المقدار.**
#    الكتاب يكتب المركّب بلا فراغ («ن+٢ ق ر») والجمعَ الثنائيّ بفراغ
#    («٩ ق ر + ٩ ق (ر-١)»). ولمّا سمحتُ بالفراغ ابتلع المقدارُ الجمعَ
#    فخرج «\\comb{9}{ر + 9}» — وتلفت معه المطابقةُ التالية.
_TIGHT = r"(?:" + _ATOM + r"(?:[-−+]" + _ATOM + r")?)"
# ⚖️ و«[ ]» فراغُ ملءٍ في تمارين المنطق: «^[ ] ل_[ ] = ٧ × ٦».
#    مقدارٌ مقصودٌ خالٍ، فيُرسم رمزاً بفراغٍ لا يُترك «^» عاريةً.
_BLANK = r"\[[^\]]{0,4}\]"
_OPERAND = r"(?:" + _BLANK + r"|\(\s*" + _TIGHT + r"\s*\)|" + _TIGHT + r")"
# داخل «ل( … ، … )» الفاصلةُ تفصل، فلا خطرَ من الفراغ حول الإشارة.
_LOOSE = r"(?:" + _ATOM + r"(?:\s*[-−+]\s*" + _ATOM + r")?)"

_LETTER = r"(?P<L>[لق])"
_NOT_AR_BEFORE = r"(?<![" + _ARABIC + r"])"
_NOT_AR_AFTER = r"(?![" + _ARABIC + r"])"

# ١) صيغة الدالّة: «ل(ن، ر)» — أكثرُ ما في كتاب الرياضيات.
_FUNC = re.compile(
    _NOT_AR_BEFORE + _LETTER + r"\s*\(\s*(?P<N>" + _LOOSE + r")\s*[،,]\s*"
    r"(?P<R>" + _LOOSE + r")\s*\)")

# ٢) صيغة الأُسّ والحرف المنخفض: «^6 ل_6» و«^20 ق_{2س-1}» — كتاب المنطق.
_SUB = re.compile(
    r"\^\s*(?P<N>" + _OPERAND + r")\s*" + _LETTER
    + r"\s*_\s*(?:\{\s*(?P<RB>[^{}]{1,12}?)\s*\}|(?P<R>" + _OPERAND + r"))"
    + _NOT_AR_AFTER)

# ٣) الصيغة المقوّسة: «(ن ق 0)» — مفكوك ذات الحدين.
_PAREN = re.compile(
    r"\(\s*(?P<N>" + _OPERAND + r")\s+" + _NOT_AR_BEFORE + _LETTER
    + _NOT_AR_AFTER + r"\s+(?P<R>" + _OPERAND + r")\s*\)")

# ٤) الصيغة العارية: «6 ل 2» — تلزمها مسافةٌ صريحة على الجانبين، وإلا
#    التقطت «ن ق١» (بؤرة القطع الناقص) و«ق س» (مركّبة القوة).
_BARE = re.compile(
    r"(?<![" + _ARABIC + r"0-9٠-٩(])(?P<N>" + _OPERAND + r")\s+"
    + _NOT_AR_BEFORE + _LETTER + _NOT_AR_AFTER + r"\s+(?P<R>" + _OPERAND + r")"
    + r"(?![" + _ARABIC + r"0-9٠-٩])")

_TOKEN = {"ل": "perm", "ق": "comb"}


def _sub(m: "re.Match") -> str:
    groups = m.groupdict()
    right = groups.get("RB") or groups.get("R") or ""
    return "\\%s{%s}{%s}" % (_TOKEN[m.group("L")],
                             m.group("N").strip(" ()"), right.strip(" ()"))


def is_counting_subject(subject: str) -> bool:
    return (subject or "").strip() in COUNTING_SUBJECTS


def to_counting(text: str, subject: str = "") -> str:
    """يحوّل «ل(ن،ر)» و«ن ق ر» إلى `\\perm{}{}` / `\\comb{}{}`.

    ⚠️ في **الجبر والمنطق وحدهما**؛ وفي غيرهما «ل» و«ق» حرفا كلامٍ لا رمز.
    """
    if not text or not is_counting_subject(subject):
        return text
    if "ل" not in text and "ق" not in text:
        return text
    for rx in (_FUNC, _SUB, _PAREN, _BARE):
        text = rx.sub(_sub, text)
    return text
