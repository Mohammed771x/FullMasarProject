# -*- coding: utf-8 -*-
"""🇸🇦 عدسةُ العربي في «اختبر نفسك» — تمرينٌ على جملة لا سؤالٌ عن تعريف.

📏 **ما أوجبها (2026-09-29):** بنكُ عربي الثالث (gpt-4o-mini بالمواصفة العامة)
   أسئلتُه «ما تعريف المفعول لأجله؟» و«ما الشرط الأول…؟» — حفظٌ لا تطبيق، وفيها
   خياراتٌ لا معنى لها («أحد أنواع المفعول لأجله: المضاف»). وطلبُ المالك:
   «العربي… كثّر أسئلة إعراب… على حسب الأسئلة والدروس، وركّز في العروض…
   بغيت حاجة بياض وجه». وأسئلةُ الكتاب نفسُه: «أعرب ما تحته خط» · «استخرج» ·
   «بيّن نوع…» · «قطّع البيت واذكر بحره» — فالبنكُ يسير على خطاه.

⚖️ **والمادّةُ تُقاس حيث هي** كما في الإنجليزية ([quiz_spec_en]): سؤالُ
   التطبيق يحمل جملتَه بين «» أو بيتَه، والكلمةُ المسؤولُ عنها بين `__…__`
   فيرسمها التطبيق خطّاً (نفس ترميز الشرح المخزون).
"""
import re

# 🎯 فرعُ الدرس من اسم وحدته ودرسه — لكلٍّ عدستُه.
_ARUD = re.compile(r"العروض|بحر\s")
_BALAGHA = re.compile(r"البلاغة|بلاغ|التشبيه|الاستعارة|الكناية|المجاز|الطباق|"
                      r"المقابلة|الجناس|السجع|الخبر|الإنشاء|الاستفهام|النداء|"
                      r"الأمر|النهي|التمني|القصر|الإيجاز|الإطناب|التقديم")


def branch(lesson: str, source: str = "") -> str:
    """«عروض» · «بلاغة» · «نحو» — من اسم الدرس ووحدته."""
    head = (source or "").split("\n", 1)[0] + " " + (lesson or "")
    if _ARUD.search(head):
        return "عروض"
    unit = (source or "").split("\n", 1)[0]
    if "البلاغة" in unit or ("النحو" not in unit and _BALAGHA.search(lesson or "")):
        return "بلاغة"
    return "نحو"


def arabic_quota(count: int) -> tuple:
    """(تطبيق، تعريفٌ أقصى) — ثلاثةُ أرباعٍ تطبيق، ونُزرٌ للمفاهيم."""
    applied = max(2, round(count * 0.75))
    return applied, max(1, count - applied)


_NAHW = """
🔤 **درسُ نحوٍ وصرف — الإعرابُ قلبُه:**
• **«أعرب ما تحته خط»** أكثرُ ما تكتب: جملةٌ كاملةٌ مشكولةٌ بين «» والكلمةُ
  المسؤولُ عنها بين `__…__`، والخياراتُ أربعةُ إعراباتٍ **تامّة** (الوظيفة +
  العلامة + سببها).
  ✅ «ما إعرابُ ما تحته خطّ: «كان __الجوُّ__ صافياً»؟»
     ["اسمُ كان مرفوعٌ وعلامةُ رفعه الضمة الظاهرة",
      "مبتدأٌ مرفوعٌ وعلامةُ رفعه الضمة الظاهرة",
      "فاعلٌ مرفوعٌ وعلامةُ رفعه الضمة الظاهرة",
      "خبرُ كان مرفوعٌ وعلامةُ رفعه الضمة الظاهرة"]
• **العلامةُ الفرعية** حيث يسمح الدرس: مثنى، جمعُ مذكرٍ سالم، أسماءٌ خمسة،
  أفعالٌ خمسة، ممنوعٌ من الصرف، معتلُّ الآخر (مقدّرةٌ للتعذّر أو للثقل).
• **اختر الصواب**: «اختر الضبطَ الصحيح: «إنّ المعلمـ… مخلصون»» بخياراتٍ
  مضبوطة (المعلمين / المعلمون / المعلمَين / المعلمِين).
• **استخرج / بيّن النوع**: «في «…» الخبرُ: مفردٌ / جملةٌ فعلية / جملةٌ اسمية /
  شبهُ جملة»، «الفعلُ في «…»: تامٌّ أم ناقص؟»، «سببُ وجوب تقديم الخبر…».
• **صوّب الخطأ**: جملةٌ فيها خطأٌ نحويٌّ واحد، والخياراتُ تصويباتٌ لها.
• **الحكمُ لا يُستنتج من الموديل بل من الدرس**: القاعدةُ كما قرّرها الكتاب
  حرفاً (مثلاً: أفعالُ الشروع لا تعمل إلا بصيغة الماضي).
"""

_BALAGHA_RULES = """
🎨 **درسُ بلاغة — تحديدُ الفنّ وغرضه على شاهد:**
• شاهدٌ (آيةٌ أو بيتٌ أو قولٌ) بين «» ثم: «ما الفنُّ البلاغيُّ في …؟» ·
  «ما نوعُ التشبيه؟» (مرسل / مؤكد / مجمل / مفصل / بليغ / تمثيلي / ضمني /
  مقلوب) · «ما الغرضُ البلاغيُّ من الاستفهام / الأمر / النهي / النداء؟» ·
  «ما القرينة؟» · «ما العلاقةُ في المجاز المرسل؟» · «حدّد المقصور عليه».
• **الخياراتُ من مصطلحات الدرس نفسِه** — والمشتّتُ فنٌّ قريبٌ يُخلط به فعلاً
  (طباقٌ / مقابلة، استعارةٌ تصريحية / مكنية، تشبيهٌ بليغ / استعارة).
• **الشاهدُ يحتمل جواباً واحداً**: لا تختر بيتاً فيه طباقٌ ومقابلةٌ معاً ثم
  تسأل «ما الفن؟». وحين يحتمل الغرضُ وجهين في كتب البلاغة فاختر شاهداً آخر.
• والأغراضُ **من قائمة الدرس وحدها** — لا تُضف غرضاً لم يذكره (كالتشويق
  والتعجب إن لم يذكرهما الدرس).
"""

_ARUD_RULES = """
🎼 **درسُ عروض — التقطيعُ قلبُه، ومصدرُه تقطيعُ الكتاب نفسِه:**
📏 قِيس (2026-09-29): بلا هذا البند خرج بنكُ «بحر الكامل» بلا سؤالِ تقطيعٍ
   واحد — «كم رمزاً يصير في الصدر؟» و«أيُّ البحور ذُكر في الجزء الأول؟».

• **في الدرس أبياتٌ مقطّعةٌ كاملة** (الكتابة العروضية · الرموز · التفعيلات).
  **{arud_n} سؤالاً على الأقل تُبنى منها مباشرة**، والجوابُ الصحيح **منقولٌ
  من تقطيع الكتاب حرفاً بحرف** — فلا تقطّع أنت من عندك:
  ① «ما الكتابةُ العروضيةُ لـ «<جزءٌ من شطرٍ في الدرس>»؟» — والمشتّتاتُ
     أخطاءُ الطلاب: تركُ فكّ التضعيف، تركُ التنوين نوناً، كتابةُ همزة الوصل
     أو لام «ال» الشمسية، تركُ إشباع حركة الرويّ.
  ② «ما الرموزُ العروضيةُ لـ «<مقطعٌ في الدرس>»؟» — بـ`/` و`ه` فقط.
  ③ «ما التفعيلةُ الثانية (أو الأخيرة) في صدر / عجز «<البيت>»؟» — والمشتّتاتُ
     صورُ التغيير الأخرى التي ذكرها الدرس لهذا البحر.
  ④ «في «<البيت>» جاءت التفعيلة … على (…)؛ هذه الصورةُ من صور …» أو «هل
     البيتُ تامٌّ أم مجزوء؟» بعدِّ تفعيلاته كما في الكتاب.
• ويُكمَل البنكُ بـ: وزنُ البحر ومفتاحُه كما في الكتاب، وصورُ التغيير
  الجائزة فيه (من جدول الدرس)، و«ما بحرُ هذا البيت؟» على أبيات الدرس
  والخياراتُ البحورُ التي درسها الطالب.
• ⛔ **ممنوع**: عدُّ الرموز أو جمعُها («كم رمزاً…»)، والسؤالُ عن ترتيب
  الدرس أو أجزاء الوحدة («أيُّ البحور ذُكر في الجزء الأول»)، وتقطيعُ بيتٍ ليس
  في الدرس.
• وفي `why` انقل تقطيعَ الكتاب للموضع المسؤول عنه كما هو.
"""


def arabic_clause(count: int, lesson: str = "", source: str = "") -> str:
    applied, defs = arabic_quota(count)
    kind = branch(lesson, source)
    lens = {"عروض": _ARUD_RULES.replace("{arud_n}", str(max(3, round(count * 0.5)))),
            "بلاغة": _BALAGHA_RULES}.get(kind, _NAHW)
    return f"""

━━━━━━━━━━━━━━━━━━━━
🇸🇦 **هذا بنكُ عربي — «اختبر نفسك» تمرينٌ يحلّه الطالب، لا أسئلةُ حفظ:**

④ **تطبيقٌ على مادّة — {applied} سؤالاً على الأقل، عُدَّها.** سؤالُ التطبيق
   فيه **أمرٌ ومادّةٌ يعمل عليها** مكتوبةٌ كاملةً داخل `q`: جملةٌ أو آيةٌ أو
   بيتٌ **بين «»**، والكلمةُ المقصودةُ بين `__…__` (يُرسم تحتها خط).
   🤖 **هذا ما تعدّه الآلة حرفياً:** سؤالٌ في `q` فيه «…» بين علامتي
      التنصيص «» **أو** كلمةٌ بين `__…__`. وما خلا منهما تعريفٌ — ولك منه
      **{defs}** فقط في البنك كلّه.
   ❌ «ما تعريفُ المفعول لأجله؟» ← لا مادّة
   ❌ «ما الشرطُ الأول للمفعول لأجله؟» ← لا مادّة
   ✅ «ما إعرابُ ما تحته خطّ: «وقف الطلابُ __احتراماً__ للمعلم»؟»
   ✅ «في قوله تعالى «…» الفنُّ البلاغي:»
   ✏️ **ما قال «تحته خط» فليضع الخطّ**: `__الكلمة__` داخل الجملة نفسِها، وإلا
      فالسؤالُ بلا جواب.
{lens}
⑦ **الأمثلة: القاعدةُ من الدرس، والجملُ أكثرُها جديدة.** الطالبُ ذاكر أمثلةَ
   كتابه؛ فخذ منها **الربعَ على الأكثر**، واكتب البقيّةَ جملاً عربيةً فصيحةً
   **مشكولةً شكلاً تامّاً في موضع السؤال** تطبّق القاعدةَ نفسَها (عدا
   العروض: أبياتُه وتقطيعُها من الدرس وحده).

⑧ **الدقّةُ أوّلاً — خيارٌ صحيحٌ واحدٌ يدافع عنه معلّمُ عربي:**
   • **حُلَّ السؤالَ بنفسك مرّتين** قبل أن تكتب `correct_index`، واكتب في
     `why` الإعرابَ أو التقطيعَ أو التعليلَ **كاملاً** سطراً واحداً.
   • المشتّتُ خطأٌ يقع فيه الطالبُ فعلاً (فاعلٌ / مبتدأ، ضمةٌ ظاهرة / مقدّرة،
     حالٌ / تمييز)، لا خيارٌ لا يختاره أحد.
   • لا خيارين صحيحين: «مبتدأٌ مؤخّر» و«مبتدأٌ مرفوع» معاً في سؤالٍ واحد
     يحتملان الصواب — اجعل الخياراتِ متمايزة.
   • لا «كلُّ ما سبق» ولا «لا شيء مما ذُكر».

③ **«صعب» في العربي**: إعرابُ جملةٍ في محلّ، أو علامةٌ مقدّرةٌ أو فرعية،
   أو تقطيعُ شطرٍ كامل، أو شاهدٌ يحتاج تمييزاً بين فنّين متقاربين — لا
   تعريفٌ طويلُ الصياغة.

⑥ **`why` بالعربية سطرٌ واحدٌ مفيد** يقرؤه الطالبُ بعد الاختبار: الإعرابُ
   التامّ أو القاعدةُ التي حكمت، لا تكرارٌ لنصّ الخيار."""


