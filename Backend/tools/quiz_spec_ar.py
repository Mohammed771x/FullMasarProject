# 🤖 الفحصُ الآليّ — يصل الموديلَ في نداء التصحيح بأرقامه
# ══════════════════════════════════════════════════
_MATERIAL = re.compile(r"«[^»]{6,}»|(?<!_)__[^_\n]{1,40}__(?!_)")
_UNDERLINE_REF = re.compile(r"تحته\s*خط|تحتها\s*خط")
_MARK = re.compile(r"(?<!_)__[^_\n]{1,40}__(?!_)")
_ARUD_SYMBOLS = re.compile(r"^[\s/ه]+$")


def is_arabic_drill(q: str) -> bool:
    """سؤالُ تطبيقٍ عربيّ: يحمل شاهدَه بين «» أو كلمتَه بين __…__."""
    return bool(_MATERIAL.search(q or ""))


def arabic_defects(questions: list) -> list:
    """عيوبُ بنك العربي: تطبيقٌ ناقص، و«تحته خط» بلا خطّ، ورموزٌ عروضيةٌ مشوبة."""
    if not questions:
        return []
    bad, n = [], len(questions)
    applied = sum(1 for q in questions if _MATERIAL.search(q.get("q", "")))
    need, _ = arabic_quota(n)
    if applied < need:
        bad.append(f"التطبيق {applied} من {n} — والمطلوب {need} سؤالاً يحمل "
                   "جملةً أو شاهداً بين «» أو كلمةً بين __…__")
    unmarked = [q for q in questions
                if _UNDERLINE_REF.search(q.get("q", "")) and not _MARK.search(q.get("q", ""))]
    if unmarked:
        bad.append(f"{len(unmarked)} سؤالاً يقول «تحته خط» ولا `__…__` فيه — "
                   f"مثالٌ: «{unmarked[0].get('q', '')[:60]}»")
    # 🎼 خيارُ رموزٍ عروضية فيه غيرُ «/» و«ه» ⇒ رمزٌ لا يُقرأ.
    for q in questions:
        opts = q.get("options") or []
        sym = [o for o in opts if "/" in o and "ه" in o and len(o) < 40]
        if len(sym) == len(opts) == 4 and not all(_ARUD_SYMBOLS.match(o) for o in sym):
            bad.append(f"رموزٌ عروضيةٌ فيها غيرُ «/» و«ه»: «{q.get('q', '')[:50]}»")
            break
    return bad
