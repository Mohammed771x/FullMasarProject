    #    وضعفُ طوله إسهاب. ومعه أرضيةٌ للسقف (٦٠٠٠) لئلا يُضيَّق على درسٍ
    #    قصيرٍ صعبٍ يحتاج تفصيلاً حقيقياً. وشُدّ إلى «طولِ الدرس» بعد أن
    #    رأى المالكُ شرحاً صار «مقالاً كاملاً».
    # 🧮 **والمادةُ الحسابيةُ تحتاج مدىً أوسع**: مصدرُها قائمةُ أمثلةٍ
    #    مُوجزة، وحلُّها **بخطواته كلِّها** أطولُ من مصدره بطبعه — لا إسهاباً
    #    بل استيفاءً لما نطلبه نحن. قِيس (2026-09-16): سقطت ١٢ من ١٨ في
    #    الرياضيات بـ«مُسهِب» وهي بين ٥٣٠٠ و٦٦٠٠ حرفاً، وأكثرُها حلولٌ.
