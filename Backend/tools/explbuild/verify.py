_TEX_CMD = re.compile(r"\\[A-Za-z]+(?:\{[^{}]*\})*")


def _without_codes(text: str) -> str:
    """النصُّ بلا أوامر الترميز — لعدّ ما يراه الطالبُ حروفاً لا ما يُرسم."""
    return _TEX_CMD.sub(" ", text or "")


_NUMERIC_PART = re.compile(r"^[\s0-9٠-٩.,\^\-+×xX*()]+$")
_NUM_TOKEN = re.compile(r"[0-9٠-٩][0-9٠-٩.,]*")


def _is_numeric_substitution(code: str) -> bool:
    """كسرٌ طرفاه أرقامٌ خالصة — أي **خطوةُ تعويضٍ في مثالٍ محلول**، لا قانون.

    ⚖️ والفرقُ جوهريّ في الحكم عليه: `\frac{ع}{λ}` **قانونٌ** يجب أن يُرسم
       مكدّساً كما في الكتاب، أما `\frac{١٠٠x١٠^٦}{٣x١٠^٨}` فخطوةُ حسابٍ
       عابرة، وكتابتُها في سطرٍ واحد لا تُفقد الطالبَ شيئاً من المعنى.
    """
    m = re.match(r"\\frac\{([^{}]*)\}\{([^{}]*)\}", code or "")
    if not m:
        return False
    a, b = m.group(1), m.group(2)
    return bool(_NUMERIC_PART.match(a) and _NUMERIC_PART.match(b)
                and _NUM_TOKEN.search(a) and _NUM_TOKEN.search(b))


def _numbers_present(code: str, body: str) -> bool:
    """هل أرقامُ هذا التعويض موجودةٌ في الشرح ولو بصيغةٍ سطرية؟"""
    nums = [n for n in _NUM_TOKEN.findall(code) if len(n) > 1]
    if not nums:
        return False
    hit = sum(1 for n in nums if n in body)
    return hit >= max(1, (len(nums) + 1) // 2)


_SQRT_TEX = re.compile(r"\\sqrt\{([^{}]*)\}")
# 🔺 **الأُسُّ صيغتان يرسمهما التطبيق كلتاهما**: الكتابُ يكتب «ف^٢»
#    والموديلُ يكتب «ف\sup{٢}». وقِيس أن هذا وحده أسقط قانونَ كولوم من
#    درس «المجال الكهربائي» — وهو منقولٌ في الشرح كاملاً وصحيحاً.
_SUP_TEX = re.compile(r"\\sup\{([^{}]*)\}")
_SUB_TEX = re.compile(r"\\sub\{([^{}]*)\}")


# 🔢 **ثلاثُ صيغٍ للأُسّ الواحد في كتبنا ومخرجاتنا**، والتطبيق يرسمها كلَّها:
#      «س²» (محرفُ أُسٍّ لاتيني) · «س^٢» (قبّعة) · «س\sup{٢}» (ترميزُنا).
#    وكتابُ الرياضيات يخلط بينها في **الدرس الواحد**. وقِيس أن هذا وحده
#    أسقط `\frac{س}{س² - ٤س + ٤}` من شرحٍ كتبها `\frac{س}{س\sup{٢} - ٤س + ٤}`
#    — نفسُ الكسر حرفاً بحرف، بأُسٍّ مكتوبٍ بصيغةٍ أخرى.
#
# ⚠️ **والأرقامُ تُوحَّد للمقارنة وحدها**: «٢» العربية و«2» اللاتينية رقمٌ
#    واحد في عين الطالب، والكتبُ تخلطهما. ولا يمسّ هذا ما يُخزَّن — التطبيعُ
#    للمقارنة فقط، والمخرَجُ يُحفظ كما كتبه الموديل.
_SUPERSCRIPT = {"⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4",
                "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9"}
_SUBSCRIPT = {"₀": "0", "₁": "1", "₂": "2", "₃": "3", "₄": "4",
              "₅": "5", "₆": "6", "₇": "7", "₈": "8", "₉": "9"}
_DIGITS_UNIFY = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")


def _norm_codes(text: str) -> str:
    r"""صيغةٌ مُطبَّعة لمقارنة ترميز الرسم — الفروقُ التي يرسمها التطبيق
    سواءً بسواء لا تُعدّ سقوطاً:
      `\sqrt{س}`≡`جذر س` · `\sup{٢}`≡`^٢`≡`²` · `٢`≡`2` · والمسافات.
    """
    # ⚠️ **الترتيبُ مقصود**: الأُسُّ أوّلاً ثم الجذر. فـ`\sqrt{١ - س\sup{٢}}`
    #    فيه قوسان معقوفان داخل الجذر، ونمطُ الجذر المسطّح لا يراهما — فلو
    #    عولج الجذرُ أوّلاً بقي كما هو ولم يُطبَّع أصلاً.
    out = _SUP_TEX.sub(r"^\1", text or "")
    out = _SUB_TEX.sub(r"_\1", out)
    out = _SQRT_TEX.sub(r"جذر\1", out)
    for ch, d in _SUPERSCRIPT.items():
        out = out.replace(ch, "^" + d)
    for ch, d in _SUBSCRIPT.items():
        out = out.replace(ch, "_" + d)
    out = out.translate(_DIGITS_UNIFY)
    # 🥧 **و«باي» و«π» رمزٌ واحد** — الكتابُ يكتبها بالحروف والموديلُ
    #    بالرمز، والتطبيقُ يرسمهما سواءً بسواء. قِيس (2026-09-16): أسقط
    #    هذا وحدَه `\frac{باي}{٢}` من ثلاثة دروسٍ في دوائر التيار المتردد —
    #    والكسرُ منقولٌ في الشرح ثلاثَ مرّات صحيحاً.
    #    وهي **سادسُ** مرّةٍ يكون فيها المخطئُ مقياسي لا الموديل.
    out = out.replace("π", "باي").replace("ط]", "باي]")
    # 🧪 **و`\chem{C≡C}` يظهر للطالب `C≡C`**: الغلافُ يخدم رسّامَ الصيغ
    #    البنائية، وصيغةٌ بسيطةٌ بلا روابطَ مرسومة تُقرأ كما هي. فاختلافُ
    #    الغلاف وحده ليس سقوطَ ترميز.
    out = re.sub(r"\\chem\{([^{}]*)\}", r"\1", out)
    # 🌱 **والجذرُ يُكتب بأربع صيغٍ في كتبنا**: «جذر ٢» · «جذر(٢)» ·
    #    «\sqrt{٢}» · و«الجذر_التكعيبي(س)». والتطبيقُ يرسمها جميعاً، فلا
    #    يُعدّ اختلافُها سقوطاً. (٢٠ ترميزاً من ١٨٤ في الباقي كانت هذه وحدها.)
    # 🌱 **وخامسةٌ: محرفُ الجذر `√` نفسُه** — وهو ما يكتبه **الكتاب**
    #    («جا ٦٠ = \frac{√٣}{٢}») بينما يكتب الموديلُ `\sqrt{٣}`.
    #    والتطبيقُ يرسمهما سواءً بسواء، فاختلافُهما ليس سقوطاً.
    #    قِيس (2026-09-17) في «توازن جسمٍ صلب بثلاث قوى»: أسقط هذا وحدَه
    #    **خمسةَ** ترميزاتٍ من سبعةَ عشر — والشرحُ ناقلُها كلَّها صحيحةً.
    out = re.sub(r"√\s*", "جذر", out)
    out = re.sub(r"(?:ال)?جذر[_ ]?(?:ال)?تكعيبي\(([^()]*)\)", r"جذر3\1", out)
    out = re.sub(r"جذر\(([^()]*)\)", r"جذر\1", out)
    return re.sub(r"\s+", "", out)


