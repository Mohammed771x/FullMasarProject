# =====================
# 🎯 عتبةُ الصلة — «أفضل أربع» لا تعني «ذات صلة»
# =====================
#
# 🔴 **المشكلة (نصّ المالك 2026-09-14):** «الطالب يسأل: ما هو قانون نيوتن
#    الثاني؟ بينما الوحدة عن الغدد. البحثُ سيقول: أفضل ٤ نتائج ٥١ ٤٦ ٥٠ ٥٣.
#    لكن أفضل ٤ لا يعني أنها ذات صلة فعلاً. وهنا ممكن الموديل يستنتج: بما أن
#    هذه الصفحات هي التي أُرسلت لي، فلا بد أن أجيب منها.»
#
# 📏 **والرقمان أدناه من البيانات لا من التخمين** (نصّ المالك: «لا تختاروا
#    رقم العتبة بالتخمين — خذوا عينة حقيقية وسجلوا similarity scores، ثم
#    شوفوا التوزيع») — عيّنتان على تسعة كتب:
#
#    ① ٦٣٠ سؤالاً مبنيّاً: ٣٧٨ داخل الوحدة (متابعاتٌ وقصيرةٌ وبأخطاءٍ
#      إملائيةٍ وبضمائر) · ١٦٨ من وحدةٍ أخرى · ٨٤ خارج المادة.
#
#      العتبة   يرفض داخلَ الوحدة   يمسك خارجَ المادة   يمسك خارجَ الوحدة
#      ٠٫٤٠          ٠٫٨٪                ٧٣٫٨٪              ١٨٫٥٪
#      ٠٫٤٥          ١٫٦٪                ٨٣٫٣٪              ٢٨٫٠٪
#      ٠٫٥٠          ٢٫٦٪                ٩٢٫٩٪              ٣٩٫٩٪   ← الأرضية
#      ٠٫٦٠          ٦٫٣٪               ١٠٠٫٠٪              ٦٣٫٧٪   ← لا دخيلَ فوقها
#
#      والعشرةُ المرفوضة عند الأرضية فُحصت واحدةً واحدة: أربعةُ أخطاءٍ
#      إملائيةٍ فادحة، وأربعةُ سطورِ فهرسةٍ («سجل ذلك في كراستك»)، ومتابعتان
#      موضوعُهما المستعار سطرُ فهرسة. **ولا سؤالٌ سليمٌ واحد.**
#
#    ② **٢٦٠ سؤالاً من متن الكتب نفسِها** — كتبها مؤلّفو المناهج في الدروس
#      («لماذا تسمى الغدة النخامية ملكة غدد جسم الإنسان؟»)، فهي أصدقُ ما
#      يُقاس عليه سؤالُ طالب. **أدناها ٠٫٧١٧** وخامسُ مئينها ٠٫٨٨١ —
#      أي أن السؤال السليم لا يقترب من الأرضية أصلاً.
#
# ⚠️ **والفصلُ على المجموع الهجين لا على الجيب وحده**: عتبةٌ على التشابه
#    الدلاليّ عند ٠٫٤٠ كانت ترفض **٢٦٫٩٪** من أسئلة الوحدة.
#
# ⚖️ **والكلفتان غيرُ متماثلتين**: رفضُ سؤالٍ صحيح تجربةٌ قاسية، وقبولُ سؤالٍ
#    دخيل هو حالُنا اليوم. فالأرضيةُ حيث لا يقع سؤالٌ سليمٌ واحد.
#
# 🟡 وما بين الرقمين **لا يُرفض ولا يُصدَّق**: الصفحاتُ تُرسل ومعها أمرٌ
#    للموديل أن يقول «ليس في وحدتك» إن لم يجد الجواب — بلا نداءٍ ثانٍ.
#
# ♻️ **ويُعاد قياسُ الرقمين كلَّما تغيّر مقياسُ الدرجة** — وقد تغيّر فعلاً
